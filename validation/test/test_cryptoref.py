"""Checks of the crypto reference (cryptoref.py) and of the crypto test generators."""
import collections
import os
import random
import tempfile
import unittest

import cryptoref
import gen
import gen_crypto
import isa_forms

HERE = os.path.dirname(os.path.abspath(__file__))


class Reference(unittest.TestCase):
    def test_published_vectors_and_hashlib(self):
        # FIPS-197 C.1-C.3 and appendix B, SHA-1/SHA-256 against hashlib, GCM test case 2, GHASH by
        # PCLMULQDQ against the bitwise GCM multiplication
        self.assertEqual(cryptoref.selftest(), [])

    def test_sbox_is_a_permutation(self):
        self.assertEqual(sorted(cryptoref.SBOX), list(range(256)))
        self.assertTrue(all(cryptoref.INV_SBOX[cryptoref.SBOX[x]] == x for x in range(256)))

    def test_round_inverses(self):
        rng = random.Random(5)
        for _ in range(100):
            s, k = rng.getrandbits(128), rng.getrandbits(128)
            # AESDECLAST undoes AESENCLAST; AESIMC undoes MixColumns
            self.assertEqual(cryptoref.aesdeclast(cryptoref.aesenclast(s, k) ^ k, 0), s)
            mc = cryptoref.from_bytes(cryptoref.mix_columns(cryptoref.to_bytes(s)))
            self.assertEqual(cryptoref.aesimc(mc), s)

    def test_system_test_table_is_current(self):
        with tempfile.TemporaryDirectory() as d:
            out = os.path.join(d, 'crypto_cases.h')
            cryptoref.table(out)
            with open(out) as a, open(os.path.join(HERE, 'sys', 'crypto_cases.h')) as b:
                self.assertEqual(a.read(), b.read(), 'regenerate: cryptoref.py table sys/crypto_cases.h')


class Generators(unittest.TestCase):
    def test_forms_are_implemented_and_narrow(self):
        for (map_, pfx, op), _ in cryptoref.FORMS.items():
            pp = {0: 0, 0x66: 1}[pfx]
            self.assertFalse(isa_forms.not_yet_implemented('legacy', map_, pp, op))
            self.assertTrue(isa_forms.defined('legacy', map_, pp, op))
            for other in range(4):
                if other != pp:   # the other prefixes stay #UD (generated by the 'ud' family)
                    self.assertFalse(isa_forms.defined('legacy', map_, other, op), (map_, other, op))
        for feat in ('aes', 'pclmulqdq', 'sha'):
            self.assertTrue(isa_forms.model_has(feat))

    def test_ext_vectors(self):
        random.seed(3)
        names = collections.Counter()
        for _ in range(3000):
            g = gen.Gen()
            insn = gen_crypto.gen(g)
            self.assertLessEqual(len(insn), 15)
            self.assertTrue(g.desc.startswith('crypto-'))
            name, reg, src, hexa, imm = g.desc[len('crypto-'):].split(':')
            self.assertEqual(bytes.fromhex(hexa), insn)
            names[name] += 1
            if src.startswith('m'):
                ea = int(src[1:], 16)
                self.assertTrue(gen.DATA <= ea <= gen.DATA + gen.DATA_SIZE - 16)
                if name.startswith('sha'):
                    self.assertEqual(ea % 16, 0)
        self.assertEqual(set(names), set(cryptoref.FORMS.values()))

    def test_native_families(self):
        import fp_cases
        import native_fp
        fams = {f.__name__: req for f, req in fp_cases.FAMILIES}
        self.assertEqual(fams['aes_cases'], ('aes',))
        self.assertEqual(fams['pclmul_cases'], ('pclmulqdq',))
        self.assertEqual(fams['sha_cases'], ('sha',))
        for req in fams.values():
            for f in req:
                self.assertIn(f, native_fp.FEATURES)
        rng = random.Random(1)
        import native_crypto
        imms = {m['code'][-2:] for _, m in native_crypto.pclmul_cases(rng, 10) if m['code'].startswith('660f3a44c1')}
        self.assertEqual(len(imms), 256)


if __name__ == '__main__':
    unittest.main()
