/* --- model-only (expected values in model-only.expected, derived from the manuals) --- */

void test_xsave_model(void) {
	u32 r[4];
	WRCR(0, (RDCR(0) & ~0x8000000C) | 0x22);
	cr4xs(1);
	xsetbv(0, 7);
	__asm__ volatile("fninit");
	/* CPUID 0xD.1: XSAVEOPT, XSAVEC, XGETBV1, XSAVES; compacted size for XCR0 | IA32_XSS */
	cpuid(0xD, 1, r);
	u32 e7 = r[0], b7 = r[1];
	xsetbv(0, 3); cpuid(0xD, 1, r); xsetbv(0, 7);
	u32 b3 = r[1];
	cpuid(0x80000008, 0, r);
	kprintf("xsavem.leafd.1: eax=%x ebx=%x xcr0=3: ebx=%x xsaveerptr=%x\n", e7, b7, b3, r[1] & 4);

	/* IA32_XSS: reads 0, only 0 can be written (no supervisor component on the 7742) */
	u64 x0 = rdmsr(0xDA0);
	int w0 = TRY(wrmsr(0xDA0, 0)), w1 = TRY(wrmsr(0xDA0, 1ull << 11)), w2 = TRY(wrmsr(0xDA0, 1ull << 12)),
	    w3 = TRY(wrmsr(0xDA0, 1)), w4 = TRY(wrmsr(0xDA0, 1ull << 32));
	kprintf("xsavem.xss: rd=%x wr0=%x cet_u=%x cet_s=%x x87=%x hi=%x\n", (u32)x0, w0, w1, w2, w3, w4);

	/* XSAVEC/XSAVES/XRSTORS: CR4.OSXSAVE, CR0.TS, CPL, prefixes, alignment, XRSTORS of a standard area */
	extern char u_xsaves[], u_xrstors[], u_xsavec[];
	memset(area, 0, 1024);
	xop(2, area, 7);
	int s1 = run_user(u_xsaves, 0, (u32)area), s2 = run_user(u_xrstors, 0, (u32)area), s3 = run_user(u_xsavec, 0, (u32)area);
	WRCR(0, RDCR(0) | 8);
	int t1 = xop(2, area, 7), t2 = xop(3, area, 7), t3 = xop(5, area, 7);
	int t4 = run_user(u_xsaves, 0, (u32)area);
	WRCR(0, RDCR(0) & ~8);
	cr4xs(0);
	int o1 = xop(2, area, 7), o2 = xop(3, area, 7), o3 = xop(5, area, 7);
	cr4xs(1);
	xsetbv(0, 7);
	int a1 = xop(2, area + 32, 7), a2 = xop(3, area + 16, 7), a3 = xop(5, area + 8, 7);
	memset(area, 0, 1024);
	int std = xop(5, area, 7);
	kprintf("xsavem.priv: user: xsaves=%x xrstors=%x xsavec=%x ts: xsavec=%x xsaves=%x xrstors=%x user_ts=%x noosxsave: %x %x %x align: %x %x %x xrstors_std=%x",
		s1, s2, s3, t1, t2, t3, t4, o1, o2, o3, a1, a2, a3, std);
	kprintf(" 66xsavec=%x f3xsaves=%x xrstors_reg=%x\n",
		TRY(__asm__ volatile(".byte 0x66,0x0f,0xc7,0x20" :: "a"(area), "d"(0) : "memory")),
		TRY(__asm__ volatile(".byte 0xf3,0x0f,0xc7,0x28" :: "a"(area), "d"(0) : "memory")),
		TRY(__asm__ volatile(".byte 0x0f,0xc7,0xd8")));

	/* XSETBV at CPL 3 with CR4.OSXSAVE = 0: #UD (decode fault) before #GP (also in the compared part,
	   with a rule); XSETBV in virtual-8086 mode is a CPL-3 #GP as well */

	/* XINUSE and XGETBV(1): XRSTOR initializing everything gives 0; MXCSR != 1F80H sets bit 1 in
	   XGETBV(1) only; a non-zero register sets its bit; XRSTOR loading zeros keeps the bits set */
	memset(setup, 0, 1024);
	*(u32 *)(setup + 24) = 0x1F80;
	xop(4, setup, 7);                         /* XSTATE_BV = 0: all initialized, XINUSE = 0 */
	u32 i0, i1, i2, i3, i4, i5;
	xgetbv_t(1); i0 = (u32)xgv;
	__asm__ volatile("ldmxcsr %0" :: "m"((u32){ 0x1F81 }));
	xgetbv_t(1); i1 = (u32)xgv;
	__asm__ volatile("ldmxcsr %0" :: "m"((u32){ 0x1F80 }));
	__asm__ volatile("fld1");
	xgetbv_t(1); i2 = (u32)xgv;
	__asm__ volatile("fstp %%st(0)\n fninit" ::: "memory");
	xgetbv_t(1); i3 = (u32)xgv;               /* FNINIT leaves R7 = 1.0: still in use */
	memset(setup, 0, 1024);
	*(u16 *)setup = 0x37F;
	*(u32 *)(setup + 24) = 0x1F80;
	put64(setup + 512, 7);
	xop(4, setup, 7);                         /* load the initial values: tracked as in use */
	xgetbv_t(1); i4 = (u32)xgv;
	xsetbv(0, 3);
	xgetbv_t(1); i5 = (u32)xgv;
	xsetbv(0, 7);
	kprintf("xsavem.xinuse: init=%x mxcsr=%x fld1=%x fninit=%x loaded=%x xcr0=3:%x\n", i0, i1, i2, i3, i4, i5);

	/* init optimization: XSAVE writes XSTATE_BV[i] = XINUSE[i] but saves the component; XSAVEOPT and
	   XSAVEC skip components not in use; XSAVEC still saves SSE when MXCSR != 1F80H */
	memset(setup, 0, 1024);
	*(u32 *)(setup + 24) = 0x1F80;
	xop(4, setup, 7);
	memset(area, 0xEE, 1024);
	xop(0, area, 7);
	u32 bv0 = (u32)get64(area + 512), fcw0 = *(u16 *)area, x0b = area[160], y0 = area[576];
	memset(area, 0xEE, 1024);
	xop(1, area, 7);
	u32 bv1 = (u32)get64(area + 512), fcw1 = *(u16 *)area, mx1 = *(u32 *)(area + 24), x1b = area[160], y1 = area[576];
	memset(area, 0xEE, 1024);
	xop(2, area, 7);
	u32 bv2 = (u32)get64(area + 512), cb2 = (u32)(get64(area + 520) >> 32), mx2 = *(u32 *)(area + 24);
	__asm__ volatile("ldmxcsr %0" :: "m"((u32){ 0x1F00 }));
	memset(area, 0xEE, 1024);
	xop(3, area, 7);
	u32 bv3 = (u32)get64(area + 512), mx3 = *(u32 *)(area + 24), x3b = area[160];
	__asm__ volatile("ldmxcsr %0" :: "m"((u32){ 0x1F80 }));
	kprintf("xsavem.initopt: xsave bv=%x fcw=%x xmm=%x ymm=%x xsaveopt bv=%x fcw=%x mxcsr=%x xmm=%x ymm=%x xsavec bv=%x comp=%x mxcsr=%x xsaves(mxcsr) bv=%x mxcsr=%x xmm=%x\n",
		bv0, fcw0, x0b, y0, bv1, fcw1, mx1, x1b, y1, bv2, cb2, mx2, bv3, mx3, x3b);

	/* modified optimization: an XSAVEOPT (XSAVES) directly after an XRSTOR (XRSTORS) of the same area
	   skips the restored components; here FSW.B is set in the area without ES, which loading clears,
	   so a skipped x87 save keeps the area's FSW */
	gen_state(5, 0, 0);
	memset(area, 0, 1024);
	xop(0, area, 7);
	*(u16 *)(area + 2) |= 0x8000;
	*(u16 *)area |= 0x3F;
	u32 lo = 7, hi = 0;
	__asm__ volatile("xrstor (%0)\n xsaveopt (%0)" :: "r"(area), "a"(lo), "d"(hi) : "memory");
	u32 fa = *(u16 *)(area + 2);
	__asm__ volatile("xrstor (%0)\n nop\n xsaveopt (%0)" :: "r"(area), "a"(lo), "d"(hi) : "memory");
	u32 fb = *(u16 *)(area + 2);
	*(u16 *)(area + 2) |= 0x8000;
	__asm__ volatile("xrstor (%0)\n xsaveopt (%1)" :: "r"(area), "r"(scratch), "a"(lo), "d"(hi) : "memory");
	u32 fc = *(u16 *)(scratch + 2), fd = *(u16 *)(area + 2);
	memset(area, 0, 1024);
	xop(2, area, 7);
	*(u16 *)(area + 2) |= 0x8000;
	__asm__ volatile("xrstors (%0)\n xsaves (%0)" :: "r"(area), "a"(lo), "d"(hi) : "memory");
	u32 fe = *(u16 *)(area + 2);
	__asm__ volatile("xrstors (%0)\n xsavec (%0)" :: "r"(area), "a"(lo), "d"(hi) : "memory");
	u32 ff = *(u16 *)(area + 2);
	*(u16 *)(area + 2) |= 0x8000;
	__asm__ volatile("xrstor (%0)\n xsaves (%0)" :: "r"(area), "a"(lo), "d"(hi) : "memory");
	u32 fg = *(u16 *)(area + 2);
	kprintf("xsavem.modopt: next=%x after_nop=%x other_area=%x/%x xsaves_next=%x xsavec_next=%x xsaves_after_xrstor=%x\n",
		fa, fb, fc, fd, fe, ff, fg);

	/* error pointers (XSaveErPtr): XSAVE writes FOP/FIP/FCS/FDP/FDS only with FSW.ES = 1, XRSTOR loads
	   them always (FXSAVE, unchanged, always writes them) */
	for (int es = 0; es < 2; es++) {
		memset(setup, 0, 1024);
		*(u16 *)(setup + 0) = es ? 0x37E : 0x37F;       /* IM unmasked */
		*(u16 *)(setup + 2) = es ? 0x0081 : 0x0001;     /* IE (and ES) */
		*(u16 *)(setup + 6) = 0x123; *(u32 *)(setup + 8) = 0x11223344; *(u32 *)(setup + 12) = 0x5566;
		*(u32 *)(setup + 16) = 0x778899AA; *(u32 *)(setup + 20) = 0xBBCC;
		put64(setup + 512, 1);
		xop(4, setup, 1);
		memset(area, 0, 1024);
		xop(0, area, 1);
		memset(fx, 0, 512);
		__asm__ volatile("fxsave (%0)" :: "r"(fx) : "memory");
		kprintf("%sxsave fsw=%x fop=%x fip=%x fcs=%x fdp=%x fds=%x fxsave fop=%x fip=%x fcs=%x fdp=%x fds=%x",
			es ? " es1: " : "xsavem.ptrs: es0: ", *(u16 *)(area + 2), *(u16 *)(area + 6), *(u32 *)(area + 8),
			*(u32 *)(area + 12), *(u32 *)(area + 16), *(u32 *)(area + 20), *(u16 *)(fx + 6), *(u32 *)(fx + 8),
			*(u32 *)(fx + 12), *(u32 *)(fx + 16), *(u32 *)(fx + 20));
		__asm__ volatile("fnclex\n fninit");
	}
	kputc('\n');

	/* compacted XRSTOR: format with YMM only, MXCSR initialized with SSE; standard XRSTOR of a compacted
	   area with reserved bits; XRSTOR with MXCSR reserved bits */
	gen_state(11, 0, 0);
	memset(area, 0, 1024);
	xop(2, area, 4);                          /* XCOMP_BV = 2^63 | 4: YMM at 576 */
	u32 cy = area[576] | area[577] << 8;
	gen_state(12, 0, 0);
	xop(4, area, 7);                          /* x87, SSE initialized (not in the format), YMM loaded */
	u32 cm;
	__asm__ volatile("stmxcsr %0" : "=m"(cm));
	xgetbv_t(1);
	u32 cx = (u32)xgv;
	memset(scratch, 0, 1024);
	xop(0, scratch, 4);
	put64(area + 528, 1);
	int cr = xop(4, area, 7);
	put64(area + 528, 0);
	*(u32 *)(area + 24) = 0x10000;
	put64(area + 520, 0); put64(area + 512, 2);
	int mr = xop(4, area, 2);
	kprintf("xsavem.compact: ymm=%x/%x mxcsr=%x xinuse1=%x rsvd=%x mxcsr_rsvd=%x\n", cy, scratch[576] | scratch[577] << 8, cm, cx, cr, mr);

	/* segment limit: an area beyond the DS limit (#GP(0)), on the stack beyond SS (#SS(0)) */
	u64 old30 = gdt[30];
	gdt[30] = seg_desc((u32)area, 575, 0x92, 0x4);         /* the area's first 576 bytes */
	struct { u16 lim; u32 base; } __attribute__((packed)) gd = { 8 * GDT_ENTRIES - 1, (u32)gdt };
	__asm__ volatile("lgdt %0" :: "m"(gd));
	u16 ds;
	__asm__ volatile("movw %%ds, %0" : "=r"(ds));
	int sl = TRY(__asm__ volatile("movw %1, %%ds\n xsave (%0)\n movw %2, %%ds" :: "r"(0), "r"((u16)0xF0), "r"(ds), "a"(7), "d"(0) : "memory"));
	__asm__ volatile("movw %0, %%ds" :: "r"(ds));
	int sl2 = TRY(__asm__ volatile("movw %1, %%ds\n xsave (%0)\n movw %2, %%ds" :: "r"(0), "r"((u16)0xF0), "r"(ds), "a"(1), "d"(0) : "memory"));
	__asm__ volatile("movw %0, %%ds" :: "r"(ds));
	u32 sle = last.err;
	gdt[30] = old30;
	kprintf("xsavem.seg: xsave=%x err=%x x87only=%x\n", sl, sle, sl2);

	/* the reference table (xsaveref.py) */
	u32 bad = 0, nvec = 0;
	for (u32 c = 0; c < sizeof xcases / sizeof xcases[0]; c++) {
		const struct xcase *x = &xcases[c];
		gen_state(x->seed, x->init, 0);
		gen_memory(x->seed);
		if (x->op >= 4) {
			put64(area + 512, x->bv); put64(area + 520, x->comp);
			for (int w = 0; w < 6; w++) put64(area + 528 + 8 * w, 0);
			if (x->ridx < 6) put64(area + 528 + 8 * x->ridx, x->rval);
			if (x->mx != 0xFFFFFFFF) *(u32 *)(area + 24) = x->mx;
			*(u16 *)(area + 2) = x->fsw;
		}
		xsetbv(0, x->xcr0);
		int v = xop(x->op, area, x->mask);
		xgetbv_t(1);
		u32 x1 = (u32)xgv, mh = area_hash(1), sh = state_hash();
		if (v != 0xFFFF) nvec++;
		if ((u32)v != x->vec || mh != x->memh || sh != x->sth || x1 != x->xinuse1) {
			if (bad < 5) kprintf("xsavem.table %d %s: v=%x/%x mem=%x/%x st=%x/%x xinuse1=%x/%x\n", c, opname[x->op],
				v, x->vec, mh, x->memh, sh, x->sth, x1, x->xinuse1);
			bad++;
		}
	}
	kprintf("xsavem.table: n=%d faults=%d bad=%d\n", sizeof xcases / sizeof xcases[0], nvec, bad);
	xsetbv(0, 7);
	__asm__ volatile("fninit");
}

