/* x87 transcendental instructions.
   test_x87_trans: F2XM1, FYL2X, FYL2XP1 and FPATAN fuzzed against QEMU's softfloat (masked exceptions;
   C1 is not printed, QEMU lacks it). Where QEMU's line differs from the exact reference x87ref.py, the
   rule generated into x87t-deviations.txt replaces it (see README "System tests").
   test_x87_trans_model (MODEL-ONLY): the table x87t_cases.h generated by x87ref.py for all eight
   instructions (FSIN/FCOS/FPTAN/FSINCOS use host doubles in QEMU, so it is no reference), checking
   ST(0), ST(1) and the status word including C1, C2 and TOP; then stack faults and unmasked
   responses with SDM-derived expectations in model-only.expected. */
#include "sys.h"

typedef struct { u64 sig; u16 se; } __attribute__((packed)) f80;
struct x87tcase { u32 op, cw, sw; f80 a, b, r1, r2; };
#include "x87t_cases.h"

static u32 rs = 0x7A3C91E5;
static u32 rnd(void) { rs ^= rs << 13; rs ^= rs >> 17; rs ^= rs << 5; return rs; }
static u64 rnd64(void) { u64 h = rnd(); return (h << 32) | rnd(); }

__attribute__((used)) f80 TA, TB, TR1, TR2;
__attribute__((used)) u16 TCW, TSW;

/* op numbers as in x87ref.py: 0 F2XM1, 1 FYL2X, 2 FYL2XP1, 3 FPATAN, 4 FSIN, 5 FCOS, 6 FPTAN, 7 FSINCOS */
#define RUN(opc) __asm__ volatile("fninit\n fldcw TCW\n fldt TB\n fldt TA\n .byte 0xd9," #opc \
	"\n fnstsw TSW\n fstpt TR1\n fstpt TR2\n fninit" ::: "memory")
static void run(u32 op) {
	switch (op) {
	case 0: RUN(0xf0); break;
	case 1: RUN(0xf1); break;
	case 2: RUN(0xf9); break;
	case 3: RUN(0xf3); break;
	case 4: RUN(0xfe); break;
	case 5: RUN(0xff); break;
	case 6: RUN(0xf2); break;
	default: RUN(0xfb); break;
	}
}

static void p80(const f80 *x) { kprintf(" %x_%x%x", (u32)x->se, (u32)(x->sig >> 32), (u32)x->sig); }

/* any operand class, as in t_x87.c */
static void gspecial(f80 *x) {
	u32 cls = rnd() % 12;
	u16 sign = (rnd() & 1) ? 0x8000 : 0;
	u64 s = rnd64();
	u16 e;
	switch (cls) {
	case 0: s = 0; e = 0; break;
	case 1: s &= ~(1ULL << 63); s >>= rnd() % 63; if (!s) s = 1; e = 0; break;     /* denormal */
	case 2: s |= 1ULL << 63; e = 0; break;                                        /* pseudo-denormal */
	case 3: s = 1ULL << 63; e = 0x7FFF; break;                                    /* infinity */
	case 4: s |= 3ULL << 62; e = 0x7FFF; break;                                   /* QNaN */
	case 5: s = (s & ~(3ULL << 62)) | (1ULL << 63) | 1; e = 0x7FFF; break;        /* SNaN */
	case 6: s &= ~(1ULL << 63); e = 1 + rnd() % 0x7FFE; break;                    /* unnormal */
	case 7: s |= 1ULL << 63; e = 0x7FFE - rnd() % 3; break;                       /* huge */
	case 8: s |= 1ULL << 63; e = 1 + rnd() % 3; break;                            /* tiny */
	case 9: s = 1ULL << 63; e = 16383 - 64 + rnd() % 128; break;                  /* power of two */
	default: s |= 1ULL << 63; e = 1 + rnd() % 0x7FFE; break;
	}
	x->sig = s; x->se = sign | e;
}

static void gfin(f80 *x, u32 elo, u32 ehi, int sign) {
	x->sig = rnd64() | (1ULL << 63);
	x->se = (u16)((sign ? 0x8000 : 0) | (elo + rnd() % (ehi - elo + 1)));
}

static void gen(u32 op, f80 *a, f80 *b) {
	u32 k = rnd() % 10;
	int sa = rnd() & 1;
	if (op == 0) {           /* F2XM1: -1 <= x <= 1 */
		if (k == 0) { a->sig = rnd64() >> (1 + rnd() % 63); a->se = 0; }
		else if (k == 1) gfin(a, 1, 16383 - 65, 0);
		else if (k == 2) { a->sig = 1ULL << 63; a->se = 16383; }
		else if (k == 3) { a->sig = ~0ULL - rnd() % 1000; a->se = 16382; }
		else gfin(a, 16383 - 70, 16382, 0);
		a->se |= sa ? 0x8000 : 0;
	} else if (op == 1) {    /* FYL2X: x > 0 */
		if (k == 0) { a->sig = 1ULL << 63; a->se = 1 + rnd() % 0x7FFE; }
		else if (k == 1) { a->sig = (1ULL << 63) + rnd() % 1000; a->se = 16383; }
		else if (k == 2) { a->sig = ~0ULL - rnd() % 1000; a->se = 16382; }
		else if (k == 3) { a->sig = rnd64() >> (1 + rnd() % 63); a->se = 0; }
		else if (k == 4) gfin(a, 1, 0x7FFE, 0);
		else gfin(a, 16383 - 100, 16383 + 100, 0);
	} else if (op == 2) {    /* FYL2XP1: sqrt2/2 - 1 <= x <= sqrt2 - 1 */
		if (k == 0) { a->sig = rnd64() >> (1 + rnd() % 63); a->se = 0; }
		else if (k == 1) gfin(a, 1, 16383 - 70, 0);
		else if (k == 2) { a->sig = (sa ? 0x95F619980C4336F7ULL : 0xD413CCCFE7799211ULL) - 2 + rnd() % 5; a->se = 16381; }
		else gfin(a, 16381 - 70, 16381, 0);
		a->se |= sa ? 0x8000 : 0;
	} else {                 /* FPATAN */
		if (k == 0) gfin(a, 1, 0x7FFE, sa);
		else gfin(a, 16383 - 70, 16383 + 70, sa);
	}
	if (rnd() % 6 == 0) gspecial(a);
	if (op == 3 && k > 0 && k < 4) { u32 e = a->se & 0x7FFF; gfin(b, e > 200 ? e - 200 : 1, e < 0x7F00 ? e + 200 : 0x7FFE, rnd() & 1); }
	else if (op == 3) gfin(b, 16383 - 70, 16383 + 70, rnd() & 1);
	else if (rnd() % 4 == 0) gfin(b, 1, 0x7FFE, rnd() & 1);
	else gfin(b, 16383 - 70, 16383 + 70, rnd() & 1);
	if (rnd() % 6 == 0) gspecial(b);
}

void test_x87_trans(void) {
	WRCR(0, (RDCR(0) & ~0xC) | 0x22);
	rs = fuzz_seed(rs);
	u32 n = param("x87t", 3000);
	for (u32 i = 0; i < n; i++) {
		u32 op = i % 4;
		gen(op, &TA, &TB);
		TCW = 0x7F | ((rnd() % 4) << 8) | ((rnd() % 4) << 10);
		run(op);
		kprintf("x87t %d op=%d cw=%x a", i, op, (u32)TCW); p80(&TA); kputs(" b"); p80(&TB);
		kputs(" ->"); p80(&TR1);
		kprintf(" sw=%x de=%d\n", TSW & 0x3D, (TSW >> 1) & 1);
	}
}

static int eq80(const f80 *x, const f80 *y) { return x->sig == y->sig && x->se == y->se; }

__attribute__((used)) f80 TINF = { 1ULL << 63, 0x7FFF };
__attribute__((used)) f80 TONE = { 1ULL << 63, 0x3FFF };
__attribute__((used)) f80 TDEN = { 1ULL << 62, 0 };
__attribute__((used)) f80 TNEG = { 0xA000000000000000ULL, 0xC000 };   /* -2.5 */
__attribute__((used)) f80 TXR[2];
__attribute__((used)) u16 TCW2, TSW2;

void test_x87_trans_model(void) {
	WRCR(0, (RDCR(0) & ~0xC) | 0x22);
	u32 bad = 0;
	for (u32 i = 0; i < X87T_N; i++) {
		const struct x87tcase *t = &x87t_cases[i];
		TA = t->a; TB = t->b; TCW = (u16)t->cw;
		run(t->op);
		u32 mask = 0x3FFF & ~0x4100 & ~(t->op >= 4 ? 0 : 0x400) & ~0x80;
		if (!eq80(&TR1, &t->r1) || !eq80(&TR2, &t->r2) || (TSW & mask) != t->sw) {
			bad++;
			kprintf("x87t.bad %d op=%d cw=%x a", i, t->op, t->cw); p80(&t->a); kputs(" b"); p80(&t->b);
			kputs(" ->"); p80(&TR1); p80(&TR2); kprintf(" sw=%x want", TSW & mask);
			p80(&t->r1); p80(&t->r2); kprintf(" sw=%x\n", t->sw);
		}
	}
	kprintf("x87t.table: n=%d bad=%d\n", X87T_N, bad);

	/* FPTAN with ST(7) in use: stack overflow, C1 = 1; masked: indefinite in both destinations */
	__asm__ volatile("fninit\n fld1\n fld1\n fld1\n fld1\n fld1\n fld1\n fld1\n fld1\n .byte 0xd9,0xf2\n"
	                 " fnstsw TSW2\n fstpt TXR\n fstpt TXR+10\n fninit" ::: "memory");
	kprintf("x87t.fptan.overflow: sw=%x", TSW2); p80(&TXR[0]); p80(&TXR[1]); kputc('\n');
	/* FSINCOS on an empty stack: underflow, C1 = 0; masked: indefinite in both destinations */
	__asm__ volatile("fninit\n .byte 0xd9,0xfb\n fnstsw TSW2\n fstpt TXR\n fstpt TXR+10\n fninit" ::: "memory");
	kprintf("x87t.fsincos.underflow: sw=%x", TSW2); p80(&TXR[0]); p80(&TXR[1]); kputc('\n');
	/* FYL2X with ST(1) empty: underflow; masked: ST(1) := indefinite, then pop */
	__asm__ volatile("fninit\n fld1\n .byte 0xd9,0xf1\n fnstsw TSW2\n fstpt TXR\n fninit" ::: "memory");
	kprintf("x87t.fyl2x.underflow: sw=%x", TSW2); p80(&TXR[0]); kputc('\n');
	/* unmasked IE (FSIN of infinity): ST(0) unchanged, C2 = 0, ES */
	TCW2 = 0x37E;
	__asm__ volatile("fninit\n fldcw TCW2\n fldt TINF\n .byte 0xd9,0xfe\n fnstsw TSW2\n fnclex\n fstpt TXR\n fninit" ::: "memory");
	kprintf("x87t.fsin.unmasked.ie: sw=%x", TSW2); p80(&TXR[0]); kputc('\n');
	/* unmasked DE (FPATAN, denormal ST(1)): no result, no pop */
	TCW2 = 0x37D;
	__asm__ volatile("fninit\n fldcw TCW2\n fldt TDEN\n fldt TONE\n .byte 0xd9,0xf3\n fnstsw TSW2\n fnclex\n"
	                 " fstpt TXR\n fstpt TXR+10\n fninit" ::: "memory");
	kprintf("x87t.fpatan.unmasked.de: sw=%x", TSW2); p80(&TXR[0]); p80(&TXR[1]); kputc('\n');
	/* unmasked UE (F2XM1 of 2^-16383): the result is delivered with the exponent wrapped by 24576 */
	TCW2 = 0x36F;
	__asm__ volatile("fninit\n fldcw TCW2\n fldt TDEN\n .byte 0xd9,0xf0\n fnstsw TSW2\n fnclex\n fstpt TXR\n fninit" ::: "memory");
	kprintf("x87t.f2xm1.unmasked.ue: sw=%x", TSW2); p80(&TXR[0]); kputc('\n');
	/* FYL2X(x = 0, y = -2.5): zero divide; masked: +infinity; unmasked: no result, no pop */
	__asm__ volatile("fninit\n fldt TNEG\n fldz\n .byte 0xd9,0xf1\n fnstsw TSW2\n fstpt TXR\n fninit" ::: "memory");
	kprintf("x87t.fyl2x.ze: sw=%x", TSW2); p80(&TXR[0]); kputc('\n');
	TCW2 = 0x37B;
	__asm__ volatile("fninit\n fldcw TCW2\n fldt TNEG\n fldz\n .byte 0xd9,0xf1\n fnstsw TSW2\n fnclex\n"
	                 " fstpt TXR\n fstpt TXR+10\n fninit" ::: "memory");
	kprintf("x87t.fyl2x.unmasked.ze: sw=%x", TSW2); p80(&TXR[0]); p80(&TXR[1]); kputc('\n');
}
