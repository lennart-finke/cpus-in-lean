# Generates SqMath.lean (sq_h/sq_b/sq_f) and Sq.lean (fe_sq_ok) for fe_sq.
#   python3 genmain.py <sq.txt> <dir of Solutions/OpensslX25519>
import sys
import gensq
from gensq import STREGS
from sem import Sem
import genmath

out, m = gensq.run(sys.argv[1])
D = sys.argv[2]
nfiles = (len(out) + 5) // 6

# inputs: the ten loads from fp
inputs = {}
addr_of = {}
for p in out[:3]:
    for (kind, key, nm) in p['loads']:
        if kind == 'ext':
            off = 0 if key == 'fp' else int(key.split()[-1].rstrip(')'))
            inputs[nm] = off // 4
            addr_of[nm] = key
S = Sem(inputs)
body = []
idx = 0
Nin = "B0"
flist = None
for p in out:
    Nout = f"B{idx + 1}"
    body += gensq.call_piece(p, Nin, Nout, idx, f"hS.size_eq P{idx}.1")
    for v in p['defs']:
        S.step(v, body)
    Nin = Nout
    idx += 1
NB = idx  # final body memory B{NB}, facts F{NB} P{NB}, run R{NB}
regs = m.regs
fl = m.flag
w = [regs['eax'], regs['edx'], m.slots[0x1c], m.slots[8], regs['ecx'], m.slots[0x3c], m.slots[4],
     m.slots[0x50], regs['ebp'], regs['ebx']]
fin = []
wf = [S.word(x, fin) for x in w]
carries = S.carries
Cs = ' '.join(c for (c, _, _) in carries)
hCs = ' '.join(f"h{c}" for (c, _, _) in carries)
RS = genmath.RS
XS = genmath.XS

# ---------------- SqMath.lean
mt = ["""import Solutions.OpensslX25519.MulMath
/-!
# The arithmetic of the run of `fe_sq`

Generated (`.lake/scratch/i/genmain.py`): the sums of products that `fe_sq` accumulates are the
limbs of `mulRaw f f` (`sq_h*`, ring identities by `grind`), the values it shifts are within the
signed 64-bit range (`sq_b*`), and the words it stores are the limbs of `carryChain` within the
signed 32-bit range (`sq_f*`), all by `omega` from the bounds `RawB` of the limbs.
-/
namespace Solutions.OpensslX25519
"""]
for (k, es) in S.hlemmas:
    mt.append(genmath.hlemma("sq", k, es))
for (j, tes, cs) in S.blemmas:
    mt.append(genmath.blemma("sq", j, tes, cs))
for i, f in enumerate(wf):
    mt.append(genmath.flemma("sq", i, f.es, carries))
mt.append("\nend Solutions.OpensslX25519\n")
open(D + "/SqMath.lean", "w").write("".join(mt))

