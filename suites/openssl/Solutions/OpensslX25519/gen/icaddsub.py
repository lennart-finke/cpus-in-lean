"""Call-level `fe_add`/`fe_sub` (any instruction count, return address, a 4-byte stack window).

`python3 icaddsub.py` writes I/PeelW.lean (the stack-window lemmas of Peel with the window 4),
I/AddSubRun.lean (the pieces with `ic0`) and I/AddSubCall.lean (`fe_add_call`, `fe_sub_call`),
all derived textually from the committed Peel.lean, AddSubRun.lean and AddSub.lean.
"""
import re, os
from icall import st_ic

D = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
W = 4


def blocks(src):
    """Split at top-level declarations (keeping preceding doc comments with them)."""
    return re.split(r'\n(?=(?:/--(?:(?!-/).)*?-/\n)?(?:set_option[^\n]*\n)*theorem )', src, flags=re.S)


def peelw():
    src = open(os.path.join(D, 'Peel.lean')).read()
    out, names = [], []
    for b in blocks(src):
        m = re.search(r'theorem (\S+)', b)
        if not m or not re.search(r'2048|FieldFacts', b) or 'stackBound' in b:
            continue
        n = m.group(1)
        t = re.compile(r'\n\n(?=\S)').search(b, m.start())
        if t:
            b = b[:t.start()]
        if not re.search(r'2048|FieldFacts', b):
            continue
        b = b.replace('end Solutions.OpensslX25519', '').rstrip() + '\n'
        names.append(n)
        out.append(b)
    body = '\n'.join(out)
    for n in sorted(names, key=len, reverse=True):
        body = re.sub(r'(?<![\w.])%s(?![\w])' % re.escape(n), n + 'W', body)
    body = body.replace('FieldFacts.size_eqW', 'FieldFactsW.size_eq')
    body = re.sub(r'\bFieldFacts\b(?!W)', 'FieldFactsW %d' % W, body).replace('2048', str(W))
    hdr = ('import Solutions.OpensslX25519.Peel\nimport Solutions.OpensslX25519.I.Base\n/-!\n'
           '# Stack lemmas of `Peel` for a 4-byte window\n\nGenerated by gen/icaddsub.py: the lemmas of '
           '`Peel` that mention the stack window, with the window\n`%d` (the frame of `fe_add`/`fe_sub`) '
           'instead of `stackBound`, suffixed `W`.\n-/\nnamespace Solutions.OpensslX25519\n'
           'open X86 Ssl Solutions.Logic Solutions.Exec Ssl.OpensslX25519\n\n') % W
    open(os.path.join(D, 'I', 'PeelW.lean'), 'w').write(hdr + body + '\nend Solutions.OpensslX25519\n')
    return [n for n in names if n != 'FieldFacts.size_eq']


def run():
    src = open(os.path.join(D, 'AddSubRun.lean')).read()
    names = re.findall(r'^theorem (\S+)', src, flags=re.M)
    for n in names:
        src = src.replace('theorem %s ' % n, 'theorem %s (ic0 : UInt64) ' % n, 1)
    src = st_ic(src).replace('runOk img', 'runI img')
    src = re.sub(r'\bFieldFacts\b', 'FieldFactsW %d' % W, src)
    src = src.replace('import Solutions.OpensslX25519.Call', 'import Solutions.OpensslX25519.Call\nimport Solutions.OpensslX25519.I.Base', 1)
    src = src.replace('namespace Solutions.OpensslX25519\n', 'namespace Solutions.OpensslX25519.I\n', 1)
    src = src.replace('end Solutions.OpensslX25519', 'end Solutions.OpensslX25519.I')
    src = src.replace('/-!\n', '/-! (Call-level copy at any instruction count, generated by gen/icaddsub.py.)\n', 1)
    open(os.path.join(D, 'I', 'AddSubRun.lean'), 'w').write(src)
    return names


HEAD = '''theorem fe_%(op)s_call (G : XMem) (sp h f g ret : UInt32) (fv gv : Array UInt32)
    (F0 : FieldFactsW 4 G.get.size sp.toNat h.toNat f.toNat g.toNat) (hret0 : rdRaw G.get sp 4 = ret)
    (hg0 : rdRaw G.get (sp + 4) 4 = g) (hfm : memWords G.get f 10 = fv) (hgm : memWords G.get g 10 = gv)
    (hfin : AddIn fv) (hgin : AddIn gv) (a0 ebx0 ebp0 esi0 edi0 fl0 : UInt32)
    (ic0 : UInt64) (hic : ic0.toNat < 2 ^ 63) :
    ∃ (N : XMem) (eax ecx edx fl : UInt32),
      Run img (St.m ⟨G.get, a0, h, f, ebx0, sp, ebp0, esi0, edi0, Image.sym_fe_%(op)s, efl fl0, ic0⟩)
        (St.m ⟨N.get, eax, ecx, edx, ebx0, sp + 4, ebp0, esi0, edi0, ret, efl fl, icAdd ic0 34⟩) ∧
      Pres G N (OutH (sp - 4) 4 h) ∧
      AddOut (memWords N.get h 10) ∧ feValI (memWords N.get h 10) %% pI = (feValI fv %(sym)s feValI gv) %% pI := by
'''


def main_one(blk, op, sym, pnames, wnames):
    lines = blk.split('\n')
    # drop the statement, intro, facts, obtain, let G, hS, F0
    i = next(k for k, l in enumerate(lines) if l.startswith('  obtain ⟨f1,'))
    body = '\n'.join(lines[i:])
    body = body.replace('    have := calls_arg hcall 0 (by simp)\n', '    have := hg0\n')
    body = body.replace('c.sp + 4 * (0 + 1 : Nat).toUInt32 by', 'c.sp + 4 by')
    body = body.replace('    rw [rdRaw_def]; exact this\n', '    exact this\n')
    body = body.replace('= Image.sym_halt := by', '= ret := by')
    body = body.replace('    rw [rdRaw_def]; exact calls_ret hcall\n', '    exact hret0\n')
    body = re.sub(r'  have e0 : c\.enter .*?\n  rw \[e0\]\n',
                  '  have e0 : St.m ⟨G.get, a0, h, f, ebx0, sp, ebp0, esi0, edi0, Image.sym_fe_%s, efl fl0, ic0⟩ =\n'
                  '      St.m ⟨G.get, a0, h, f, ebx0, sp, ebp0, esi0, edi0, Image.sym_fe_%s, efl fl0, icAdd ic0 0⟩ := rfl\n'
                  '  rw [e0]\n' % (op, op), body, flags=re.S)
    for a, b in [('c.regs.eax', 'a0'), ('c.regs.ebx', 'ebx0'), ('c.regs.ebp', 'ebp0'), ('c.regs.esi', 'esi0'),
                 ('c.regs.edi', 'edi0'), ('c.regs.flags', 'fl0'), ('c.sp', 'sp'), ('c.mem.size', 'G.get.size')]:
        body = body.replace(a, b)
    assert 'c.' not in re.sub(r'[\w]c\.', '', body), [l for l in body.split('\n') if 'c.' in l][:3]
    body = body.replace('run_of_runOk ', 'runIc hic ')
    for n in pnames:
        body = re.sub(r'\b%s\b' % re.escape(n), n + ' ic0', body)
    for n in sorted(wnames, key=len, reverse=True):
        body = re.sub(r'(?<![\w.])%s(?![\w])' % re.escape(n), n + 'W', body)
    body = body.replace('FieldFacts.size_eq', 'FieldFactsW.size_eq')
    # the tail
    a = body.index('  refine Returns.intro (')
    head, tail = body[:a], body[a:]
    tl = tail.split('\n')
    expr = tl[0][len('  refine Returns.intro '):]
    j = 1
    while not expr.endswith(' ?_ ?_ ?_ ?_'):
        expr += '\n' + tl[j]; j += 1
    expr = expr[:-len(' ?_ ?_ ?_ ?_')]
    rest = '\n'.join(tl[j:])
    m1 = re.search(r"    · show \(rdRaw N11\.get \(UInt32\.add \(UInt32\.sub sp 4\) 4\) 4 == Image\.sym_halt && _ && _\) = true\n(.*?)\n      rw \[hret\]; rfl\n", rest, flags=re.S)
    m2 = re.search(r"    show rdRaw N11\.get \(UInt32\.sub sp 4\) 4 = esi0\n(.*?)\n  · refine ⟨\?_, fun x hx hW hS => \?_⟩", rest, flags=re.S)
    m3 = re.search(r"    have hS' := not_inRange_stack f3 hS\n(.*?)\n  · dsimp only \[St\.m, wordsAt\]\n(.*)$", rest, flags=re.S)
    assert m1 and m2 and m3, (bool(m1), bool(m2), bool(m3))
    newtail = ('  have RR := ' + expr + '\n'
               '  have e1 : rdRaw N11.get (UInt32.add (UInt32.sub sp 4) 4) 4 = ret := by\n' + '\n'.join(l[2:] for l in m1.group(1).split('\n')) +
               '\n    exact hret\n'
               '  have e2 : rdRaw N11.get (UInt32.sub sp 4) 4 = esi0 := by\n' + m2.group(1) + '\n'
               '  rw [e1, e2, esp_retW f3] at RR\n'
               '  refine ⟨N11, _, _, _, _, RR, ⟨s11, fun x hx hP => ?_⟩, ?_⟩\n'
               '  · have hW\' := hP.2\n'
               '    have e3 : (sp - 4).toNat = sp.toNat - 4 := at_sW f3\n'
               '    have hS\' : x.toNat < sp.toNat - 4 ∨ sp.toNat ≤ x.toNat := by\n'
               '      have := hP.1; unfold OutF at this; omega\n' + m3.group(1) + '\n'
               '  · ' + m3.group(2).lstrip())
    return HEAD % {'op': op, 'sym': sym} + head + newtail


def mainproof(pnames, wnames):
    src = open(os.path.join(D, 'AddSub.lean')).read()
    a = src.index('set_option maxHeartbeats 0 in\nset_option maxRecDepth 100000 in\ntheorem fe_add_ok')
    b = src.index('set_option maxHeartbeats 0 in\nset_option maxRecDepth 100000 in\ntheorem fe_sub_ok')
    e = src.index('end Solutions.OpensslX25519')
    pre = src[:a]
    pre = pre.replace('import Solutions.OpensslX25519.AddSubRun', 'import Solutions.OpensslX25519.I.AddSubRun\nimport Solutions.OpensslX25519.I.PeelW\nimport Solutions.OpensslX25519.Frame')
    pre = pre.replace('namespace Solutions.OpensslX25519\n', 'namespace Solutions.OpensslX25519.I\n', 1)
    pre = pre.replace('/-!\n', '/-! (Call-level contracts at any instruction count and return address, generated by\ngen/icaddsub.py from the main proofs.)\n', 1)
    # helper theorems of AddSub.lean (rdRaw_def, inRange_nat, sp_sub_toNat) stay as they are
    opts = 'set_option maxHeartbeats 0 in\nset_option maxRecDepth 100000 in\n'
    add = main_one(src[a + len(opts):b], 'add', '+', pnames, wnames)
    sub = main_one(src[b + len(opts):e], 'sub', '-', pnames, wnames)
    runic = ('/-- A piece of `runI` starting `n` instructions into a call that started at `ic0`. -/\n'
             'theorem runIc {ic0 : UInt64} (hic : ic0.toNat < 2 ^ 63) {k : Nat} {m m\' : Machine} {n : Nat}\n'
             '    (h : runI img k m = some m\') (hm : m.icount = icAdd ic0 n := by rfl)\n'
             '    (hn : n + k < 2 ^ 63 := by decide) : Run img m m\' :=\n'
             '  run_of_runI h (by rw [hm]; exact icB hic hn)\n\n')
    out = pre + runic + opts + add.rstrip() + '\n\n' + opts + sub.rstrip() + '\n\nend Solutions.OpensslX25519.I\n'
    open(os.path.join(D, 'I', 'AddSubCall.lean'), 'w').write(out)


if __name__ == '__main__':
    wn = peelw()
    pn = run()
    mainproof(pn, wn)
    print('W lemmas', wn)
