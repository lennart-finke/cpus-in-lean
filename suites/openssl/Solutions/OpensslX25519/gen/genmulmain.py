# Generates MulRun01..NN.lean, MulArith.lean (mul_h/mul_b/mul_f) and Mul.lean (fe_mul_ok) for fe_mul.
#   python3 genmulmain.py <dir of Solutions/OpensslX25519> [runs]
import sys
import mulcfg
import gensq
from sem import Sem
import genmath

out, m = mulcfg.run()
D = sys.argv[1]
nfiles = (len(out) + 5) // 6
PER = 6

if len(sys.argv) > 2 and sys.argv[2] == 'runs':
    doc = '''/-!
# The run of `fe_mul`, pieces {a}–{b}

Generated (`gen/genmulmain.py`) from the disassembly: each piece runs at most eight instructions (at
most four stores) by `cbv` from a memory `N` whose frame words are listed in `l`, and states the
values it computes as single-operation equations over its inputs.
-/
'''
    hdr = gensq.HDR.replace("namespace Solutions", doc + "namespace Solutions", 1)
    for f in range(0, len(out), PER):
        a_, b_ = f, min(f + PER - 1, len(out) - 1)
        nm = f"MulRun{f // PER + 1:02d}"
        txt = hdr.format(a=a_, b=b_) + "".join(gensq.lemma(p) for p in out[a_:b_ + 1]) + \
            "\nend Solutions.OpensslX25519\n"
        open(f"{D}/{nm}.lean", "w").write(txt)
    print("runs", nfiles)
    raise SystemExit

inputs, addr_of = {}, {}
for p in out[:5]:
    for (kind, key, nm) in p['loads']:
        if kind == 'ext':
            base = key.split()[1] if key.startswith('(') else key
            off = 0 if not key.startswith('(') else int(key.split()[-1].rstrip(')'))
            inputs[nm] = off // 4 if base == 'fp' else ('Y', off // 4)
            addr_of[nm] = (base, key, off // 4)
S = Sem(inputs, two=True, pre='mul')
body = []
idx = 0
Nin = "B0"
for p in out:
    Nout = f"B{idx + 1}"
    body += gensq.call_piece(p, Nin, Nout, idx, f"hS.size_eq P{idx}.1")
    for v in p['defs']:
        S.step(v, body)
    Nin = Nout
    idx += 1
NB = idx
regs, fl = m.regs, m.flag
w = [regs['eax'], regs['edx'], m.slots[0x34], m.slots[0x20], m.slots[0x10], regs['edi'], m.slots[0],
     m.slots[0x18], regs['ebx'], regs['ebp']]
fin = []
wf = [S.word(x, fin) for x in w]
carries = S.carries
Cs = ' '.join(c for (c, _, _) in carries)
hCs = ' '.join(f"h{c}" for (c, _, _) in carries)
RS, LR = genmath.RS, genmath.LR
XS = "X0 X1 X2 X3 X4 X5 X6 X7 X8 X9"
YS = "Y0 Y1 Y2 Y3 Y4 Y5 Y6 Y7 Y8 Y9"
LX = "⟨X0, X1, X2, X3, X4, X5, X6, X7, X8, X9⟩"
LY = "⟨Y0, Y1, Y2, Y3, Y4, Y5, Y6, Y7, Y8, Y9⟩"

# ---------------- MulArith.lean
mt = ["""import Solutions.OpensslX25519.MulMath
/-!
# The arithmetic of the run of `fe_mul`

Generated (`gen/genmulmain.py`): the sums of products that `fe_mul` accumulates are the limbs of
`mulRaw f g` (`mul_h*`, ring identities by `grind`), the values it shifts are within the signed
64-bit range (`mul_b*`), and the words it stores are the limbs of `carryChain` within the signed
32-bit range (`mul_f*`), all by `omega` from the bounds `RawB` of the limbs.
-/
namespace Solutions.OpensslX25519
"""]
for (k, es) in S.hlemmas:
    mt.append(f"""
theorem mul_h{k} ({XS} {YS} : Int) :
    {es} = (mulRaw {LX} {LY}).a{k} := by
  simp only [mulRaw]
  grind
""")
for (j, tes, cs) in S.blemmas:
    mt.append(genmath.blemma("mul", j, tes, cs))
for i, f in enumerate(wf):
    mt.append(genmath.flemma("mul", i, f.es, carries))
mt.append("\nend Solutions.OpensslX25519\n")
open(D + "/MulArith.lean", "w").write("".join(mt))

