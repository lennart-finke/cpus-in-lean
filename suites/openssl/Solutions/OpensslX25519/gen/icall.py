"""Derive the call-level pieces (any instruction count) from the committed pieces.

`python3 icall.py pieces` rewrites SqRun*, MulRun*, SqEnds, MulEnds into I/ (namespace
`Solutions.OpensslX25519.I`): every running theorem takes `(ic0 : UInt64) (hic : ic0.toNat < 2 ^ 63)`
first, every machine count literal `n` becomes `icAdd ic0 n`, and `runOk`/`run_of_runOk` become
`runI`/`run_of_runI` with the bound `icB hic`. Run from Solutions/OpensslX25519/gen.
"""
import re, sys, os

D = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
PIECES = ['SqRun%02d' % i for i in range(1, 15)] + ['MulRun%02d' % i for i in range(1, 21)] + ['SqEnds', 'MulEnds']
IC = '(ic0 : UInt64) (hic : ic0.toNat < 2 ^ 63) '
B = '(icB hic (by decide))'


def st_ic(s):
    # the last component of every `St.m ⟨…, n⟩` tuple
    return re.sub(r'(St\.m ⟨[^⟩]*?), (\d+)⟩', lambda m: '%s, icAdd ic0 %s⟩' % (m.group(1), m.group(2)), s, flags=re.S)


def running_names(src):
    names = []
    for blk in re.split(r'\n(?=theorem )', src):
        m = re.match(r'theorem (\S+)', blk)
        if m and 'runOk' in blk:
            names.append(m.group(1))
    return names


def piece(src):
    names = running_names(src)
    for n in names:
        src = src.replace('theorem %s ' % n, 'theorem %s %s' % (n, IC), 1)
    src = st_ic(src)
    src = re.sub(r'run_of_runOk \(k := (\d+)\) \?_', r'run_of_runI (k := \1) ?_ ' + B, src)
    src = re.sub(r'apply run_of_runOk \(k := (\d+)\)', r'refine run_of_runI (k := \1) ?_ ' + B, src)
    src = src.replace('exact run_of_runOk h', 'exact run_of_runI h ' + B)
    src = src.replace('runOk img', 'runI img')
    assert 'runOk' not in src, 'runOk left'
    src = re.sub(r'import Solutions\.OpensslX25519\.(SqRun|MulRun|SqEnds|MulEnds)', r'import Solutions.OpensslX25519.I.\1', src)
    src = src.replace('import Solutions.OpensslX25519.Frame', 'import Solutions.OpensslX25519.Frame\nimport Solutions.OpensslX25519.I.Base', 1)
    src = src.replace('namespace Solutions.OpensslX25519\n', 'namespace Solutions.OpensslX25519.I\n', 1)
    src = src.replace('end Solutions.OpensslX25519\n', 'end Solutions.OpensslX25519.I\n')
    src = src.replace('/-!\n', '/-! (Call-level copy at any instruction count, generated by gen/icall.py.)\n', 1)
    return src, names


SQ_HEAD = '''theorem fe_sq_call (G : XMem) (sp hp fp ret : UInt32) (fv : Array UInt32)
    (F : Facts1W 464 G.get.size sp.toNat hp.toNat fp.toNat) (hret0 : rdRaw G.get sp 4 = ret)
    (hfv : memWords G.get fp 10 = fv) (hin : MulIn fv) (a0 ebx0 ebp0 esi0 edi0 fl0 : UInt32)
    (ic0 : UInt64) (hic : ic0.toNat < 2 ^ 63) :
    ∃ (N : XMem) (eax ecx edx fl : UInt32),
      Run img (St.m ⟨G.get, a0, hp, fp, ebx0, sp, ebp0, esi0, edi0, 0x102360, efl fl0, ic0⟩)
        (St.m ⟨N.get, eax, ecx, edx, ebx0, sp + 4, ebp0, esi0, edi0, ret, efl fl, icAdd ic0 574⟩) ∧
      Pres G N (OutH (sp - 464) 464 hp) ∧
      MulOut (memWords N.get hp 10) ∧ feValI (memWords N.get hp 10) % pI = feValI fv * feValI fv % pI := by
'''
MUL_HEAD = '''theorem fe_mul_call (G : XMem) (sp hp fp gp ret : UInt32) (fv gv : Array UInt32)
    (F : FieldFactsW 828 G.get.size sp.toNat hp.toNat fp.toNat gp.toNat) (hret0 : rdRaw G.get sp 4 = ret)
    (hg0 : rdRaw G.get (sp + 4) 4 = gp) (hfv : memWords G.get fp 10 = fv) (hgv : memWords G.get gp 10 = gv)
    (hfin : MulIn fv) (hgin : MulIn gv) (a0 ebx0 ebp0 esi0 edi0 fl0 : UInt32)
    (ic0 : UInt64) (hic : ic0.toNat < 2 ^ 63) :
    ∃ (N : XMem) (eax ecx edx fl : UInt32),
      Run img (St.m ⟨G.get, a0, hp, fp, ebx0, sp, ebp0, esi0, edi0, 0x100c20, efl fl0, ic0⟩)
        (St.m ⟨N.get, eax, ecx, edx, ebx0, sp + 4, ebp0, esi0, edi0, ret, efl fl, icAdd ic0 891⟩) ∧
      Pres G N (OutH (sp - 828) 828 hp) ∧
      MulOut (memWords N.get hp 10) ∧ feValI (memWords N.get hp 10) % pI = feValI fv * feValI gv % pI := by
'''


def mainproof(src, head, W, entry, names):
    lines = src.split('\n')
    i0 = next(i for i, l in enumerate(lines) if l.startswith('theorem fe_'))
    i1 = next(i for i, l in enumerate(lines) if l.startswith('  have hTop :'))
    ie = next(i for i, l in enumerate(lines) if l.startswith('  have e0 :'))
    ig = max(i for i, l in enumerate(lines) if l.startswith('  generalize c.regs.flags'))
    mid = '\n'.join(lines[i1:ie])
    mid = mid.replace('fb_toNat F.sp_lo', 'fb_toNatW F.sp_lo').replace('c.sp', 'sp').replace('c.mem.size', 'G.get.size')
    mid = mid.replace('Image.sym_halt', 'ret')
    mid = mid.replace('\n    unfold rdRaw; exact calls_ret hcall', '\n    exact hret0')
    mid = mid.replace('\n    unfold rdRaw; exact calls_arg hcall 0 (by simp)',
                      '\n    rw [show (4 : UInt32) * ((0 : Nat) + 1).toUInt32 = 4 from by decide]; exact hg0')
    assert 'hcall' not in mid, mid
    e0 = ('  have e0 : St.m ⟨G.get, a0, hp, fp, ebx0, sp, ebp0, esi0, edi0, %s, efl fl0, ic0⟩ =\n'
          '      St.m ⟨G.get, a0, hp, fp, ebx0, UInt32.add fb %d, ebp0, esi0, edi0, %s, efl fl0, icAdd ic0 0⟩ := by\n'
          '    rw [← hspfb]; rfl\n  rw [e0]') % (entry, W, entry)
    rest = lines[ig + 1:]
    j = next(i for i, l in enumerate(rest) if l.startswith('  refine Returns.intro ('))
    k = next(i for i, l in enumerate(rest) if l.startswith('  · have hw'))
    body = '\n'.join(rest[:j])
    expr = rest[j][len('  refine Returns.intro '):-len(' ?_ ?_ ?_ ?_')]
    tail = '\n'.join(rest[k:])
    tail = re.sub(r'wordsAt \(St\.m ⟨O3\.get.*?⟩\) hp 10', 'memWords O3.get hp 10', tail, flags=re.S)
    tail = tail.replace('end Solutions.OpensslX25519', 'end Solutions.OpensslX25519.I')
    newtail = ('  have hsfb : sp - %d = fb := by rw [hfb]; rfl\n'
               '  have hesp : UInt32.add fb %d = sp + 4 := by\n'
               '    rw [hspfb]\n'
               '    apply UInt32.toNat_inj.1\n'
               '    rw [toNat_uadd, UInt32.toNat_add, toNat_uadd]\n'
               '    have := hS.fit; have := hS.top; unfold ramTop at *; simp only [UInt32.reduceToNat]; omega\n'
               '  have RR := %s\n'
               '  rw [hesp] at RR\n'
               '  refine ⟨O3, _, _, _, _, RR, by rw [hsfb]; exact PO3, ?_⟩\n') % (W, W + 4, expr)
    body = body.replace('Image.sym_halt', 'ret')
    for n in names:
        body = re.sub(r'\b%s\b' % re.escape(n), n + ' ic0 hic', body)
    assert 'Image.sym_halt' not in body + tail
    pre = '\n'.join(lines[:i0])
    pre = re.sub(r'import Solutions\.OpensslX25519\.(SqRun|MulRun|SqEnds|MulEnds)', r'import Solutions.OpensslX25519.I.\1', pre)
    pre = pre.replace('import Solutions.OpensslX25519.Peel', 'import Solutions.OpensslX25519.Peel\nimport Solutions.OpensslX25519.I.Base', 1)
    pre = pre.replace('namespace Solutions.OpensslX25519\n', 'namespace Solutions.OpensslX25519.I\n', 1)
    pre = pre.replace('/-!\n', '/-! (Call-level contract at any instruction count and return address, generated by gen/icall.py\nfrom the main proof.)\n', 1)
    return pre + '\n' + head + mid + '\n' + e0 + '\n' + body + '\n' + newtail + tail


if __name__ == '__main__' and len(sys.argv) > 1 and sys.argv[1] == 'main':
    names = open(os.path.join(D, 'gen', 'icnames.txt')).read().split()
    s = mainproof(open(os.path.join(D, 'Sq.lean')).read(), SQ_HEAD, 464, '0x102360', names)
    open(os.path.join(D, 'I', 'SqCall.lean'), 'w').write(s)
    s = mainproof(open(os.path.join(D, 'Mul.lean')).read(), MUL_HEAD, 828, '0x100c20', names)
    open(os.path.join(D, 'I', 'MulCall.lean'), 'w').write(s)

if __name__ == '__main__' and len(sys.argv) > 1 and sys.argv[1] == 'pieces':
    os.makedirs(os.path.join(D, 'I'), exist_ok=True)
    allnames = []
    for p in PIECES:
        src = open(os.path.join(D, p + '.lean')).read()
        out, names = piece(src)
        allnames += names
        open(os.path.join(D, 'I', p + '.lean'), 'w').write(out)
    open(os.path.join(D, 'gen', 'icnames.txt'), 'w').write('\n'.join(allnames) + '\n')
    print(len(allnames), 'running theorems')
