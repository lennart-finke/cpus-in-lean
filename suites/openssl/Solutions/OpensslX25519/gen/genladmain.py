"""One iteration of the ladder loop of x25519_scalar_mult_generic (I/LadIter.lean, `lad_iter`), from the pieces of
genlad.py (I/LadRun1-2), the hand-written head and loop control (I/LadHead, I/LadHead2) and the call steps of the
frame state CSt (I/CSt, I/CSt2). The value of each buffer is tracked as a residue (`Rep`) of the RFC 7748 ladder.

    python3 genladmain.py          (from this directory)
"""
import os, re
from genlad import pieces, REGS, D

SQ, MUL, ADD, SUB, M121, CSWAP = 0x102360, 0x100c20, 0x100510, 0x100570, 0x103c00, 0x103b40
KCOST = {SQ: 574, MUL: 891, ADD: 34, SUB: 34, M121: 183, CSWAP: 77}
BUFS = [48, 88, 128, 168, 208, 248, 288]

HDR = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'ladmain.lean.in')).read()


def main_proof(calls):
    out = []
    a = out.append
    # after the head, lp1 and the first cswap (generated by hand in the template): registers
    reg = dict(eax='a0', ecx='c0', edx='d0', ebx='ebx', ebp='ebp', esi='pos', edi='(sw.xor bitv)', fl='f0')
    cnt = 8 + 6 + 77
    mem, C, RR = 'N0', "C0'", 'RR0'
    # buffers: off -> (bound, mfact, rfact, expr)
    buf = {88: ('M', 'm88', 'r88', 'xa'), 128: ('M', 'm128', 'r128', 'xc'), 208: ('M', 'm208', 'r208', 'xb'),
           48: ('M', 'm48', 'r48', 'xd'), 248: ('I', 'mx1', 'rx1', 'X1')}
    k = 0
    first = True
    for c in calls:
        k += 1
        if c.get('addl'):
            a(f"  have A{k} := {c['addl']} (icAdd ic1 {cnt}) (icAdd_lt hic1 (by decide)) {mem} L (hS.size_eq {C}.pres.1) "
              f"{reg['eax']} {reg['ecx']} {reg['edx']} {reg['ebx']} {reg['ebp']} {reg['esi']} {reg['edi']} {reg['fl']}")
            a(f"  simp only [icAdd_add] at A{k}")
            a(f"  have RRa{k} := {RR}.trans A{k}")
            RR = f'RRa{k}'
            reg['fl'] = '(addF 4 (UInt32.add L 4) 4 0).2'
            cnt += 1
        info = c['info']
        r = info['regs']
        args = f"{reg['eax']} {reg['ecx']} {reg['edx']} {reg['ebx']} {reg['ebp']} {reg['esi']} {reg['edi']} {reg['fl']}"
        a(f"  have P{k} := {c['piece']} (icAdd ic1 {cnt}) (icAdd_lt hic1 (by decide)) {mem} L (hS.size_eq {C}.pres.1) {args}")
        a(f"  simp only [icAdd_add] at P{k}")
        cnt += info['n']

        def val(v):
            if isinstance(v, str):
                return reg[v]
            if v[0] == 'L':
                return f'(UInt32.add L {v[1]})'
            return '0x%x' % v[1]

        def off(v):
            s = val(v)
            m = re.match(r'\(UInt32\.add L (\d+)\)', s)
            assert m, s
            return int(m.group(1))
        new = {x: val(r[x]) for x in REGS}
        ret = info['stores'][-1][1][1]
        tgt = info['target']
        ent = ' '.join((new['eax'], new['ebx'], new['ebp'], new['esi'], new['edi']))
        tail = f"{reg['fl']} ic1 {cnt} (ic_lt hic1 (by decide)) _ (by decide)"
        if tgt == CSWAP:
            # the second cswap: z2 (208) and z3 (48), bit edi = sw.xor bitv
            kf, kg = off(r['ecx']), off(r['edx'])
            assert (kf, kg) == (208, 48)
            a(f"  obtain ⟨N{k}, a{k}, c{k}, d{k}, f{k}, RR{k}, C{k}, Mf{k}, Mg{k}⟩ := {C}.cswap (by decide) (by decide) "
              f"{kf} {kg} (by decide) rfl rfl (sw.xor bitv) hbx 0x{ret:x} {ent} {tail} (by decide) ({RR}.trans P{k})")
            a(f"  have m208 : MulOut (memWords N{k}.get (UInt32.add L (208 : Nat).toUInt32) 10) := by "
              f"rw [Mf{k}]; exact bound_ite MulOut _ mz2 mz3")
            a(f"  have m48 : MulOut (memWords N{k}.get (UInt32.add L (48 : Nat).toUInt32) 10) := by "
              f"rw [Mg{k}]; exact bound_ite MulOut _ mz3 mz2")
            a(f"  have r208 : Rep (memWords N{k}.get (UInt32.add L (208 : Nat).toUInt32) 10) xb := by "
              f"rw [Mf{k}, hb2]; exact Rep_ite _ _ hiff rz2 rz3")
            a(f"  have r48 : Rep (memWords N{k}.get (UInt32.add L (48 : Nat).toUInt32) 10) xd := by "
              f"rw [Mg{k}, hd2]; exact Rep_ite _ _ hiff rz3 rz2")
            cnt += 77
        else:
            kd = off(r['ecx'])
            ks = off(r['edx'])
            if tgt in (SQ, M121):
                (bs, ms, rs, es) = buf[ks]
                if tgt == SQ:
                    hin = {'M': f'(mulIn_of_mulOut {ms})', 'A': f'(mulIn_of_addOut {ms})', 'I': ms}[bs]
                    lem, bo, expr, rep = 'sq', 'M', f'(mulp {es} {es})', f'Rep.mul {rs} {rs} Va{k}'
                else:
                    assert bs == 'A'
                    hin = ms
                    lem, bo, expr, rep = 'm121', 'M', f'(121666 * {es} % p)', f'Rep.m121 {rs} Va{k}'
                a(f"  obtain ⟨N{k}, a{k}, c{k}, d{k}, f{k}, RR{k}, C{k}, Mo{k}, Va{k}⟩ := {C}.{lem} (by decide) (by decide) "
                  f"{kd} {ks} (by simp) rfl {hin} 0x{ret:x} {ent} {tail} ({RR}.trans P{k})")
            else:
                kg = off(info['stores'][0][1])
                (bf_, mf, rf, ef) = buf[ks]
                (bg, mg, rg, eg) = buf[kg]
                if tgt in (ADD, SUB):
                    conv = lambda b, m: {'M': f'(addIn_of_mulOut {m})'}[b]
                    lem = 'add' if tgt == ADD else 'sub'
                    op = 'addp' if tgt == ADD else 'subp'
                    bo = 'A'
                    rep = f'Rep.{lem} {rf} {rg} Va{k}'
                else:
                    conv = lambda b, m: {'M': f'(mulIn_of_mulOut {m})', 'A': f'(mulIn_of_addOut {m})', 'I': m}[b]
                    lem, op, bo = 'mul', 'mulp', 'M'
                    rep = f'Rep.mul {rf} {rg} Va{k}'
                expr = f'({op} {ef} {eg})'
                a(f"  obtain ⟨N{k}, a{k}, c{k}, d{k}, f{k}, RR{k}, C{k}, Mo{k}, Va{k}⟩ := {C}.{lem} (by decide) (by decide) "
                  f"{kd} {ks} {kg} (by simp) rfl rfl {conv(bf_, mf)} {conv(bg, mg)} 0x{ret:x} {ent} {tail} (by decide) "
                  f"({RR}.trans P{k})")
            a(f"  have R{k} : Rep (memWords N{k}.get (UInt32.add L ({kd} : Nat).toUInt32) 10) {expr} := {rep}")
            buf[kd] = (bo, f'Mo{k}', f'R{k}', expr)
            cnt += KCOST[tgt]
        reg = dict(eax=f'a{k}', ecx=f'c{k}', edx=f'd{k}', ebx=new['ebx'], ebp=new['ebp'], esi=new['esi'],
                   edi=new['edi'], fl=f'f{k}')
        a(f"  have C{k}' := C{k}.set7 48 88 128 168 208 248 288 _ _ _ _ _ _ _ (by simp [keys_upd]) rfl rfl rfl rfl rfl rfl rfl")
        mem, C, RR = f'N{k}', f"C{k}'", f'RR{k}'
    # the end: addl $4 ; addl $-1, %esi ; movl 0x4(%esp), %edi ; jb
    a(f"  have AE := lad_a_end (icAdd ic1 {cnt}) (icAdd_lt hic1 (by decide)) {mem} L (hS.size_eq {C}.pres.1) "
      f"{reg['eax']} {reg['ecx']} {reg['edx']} {reg['ebx']} {reg['ebp']} {reg['esi']} {reg['edi']} {reg['fl']}")
    a(f"  simp only [icAdd_add] at AE")
    cnt += 1
    a(f"  have L1 := lc1 (icAdd ic1 {cnt}) (icAdd_lt hic1 (by decide)) {mem} L (hS.size_eq {C}.pres.1) "
      f"{reg['eax']} {reg['ecx']} {reg['edx']} {reg['ebx']} {reg['ebp']} {reg['esi']} {reg['edi']} "
      f"(addF 4 (UInt32.add L 4) 4 0).2")
    a(f"  simp only [icAdd_add] at L1")
    cnt += 1
    a(f"""  have lb : rdRaw {mem}.get (UInt32.add L 12) 4 = bitv := {C}.slot 12 bitv rfl
  have hfin : ∃ eip : UInt32, Run img (St.m ⟨{mem}.get, {reg['eax']}, {reg['ecx']}, {reg['edx']}, {reg['ebx']}, UInt32.add L 8,
      {reg['ebp']}, UInt32.add pos 4294967295, {reg['edi']}, 0x103af3, efl (addF 4 pos 4294967295 0).2, icAdd ic1 {cnt}⟩)
      (St.m ⟨{mem}.get, {reg['eax']}, {reg['ecx']}, {reg['edx']}, {reg['ebx']}, UInt32.add L 8,
      {reg['ebp']}, UInt32.add pos 4294967295, bitv, eip, efl (addF 4 pos 4294967295 0).2, icAdd ic1 ({cnt} + 2)⟩) ∧
      (pos.toNat ≠ 0 → eip = 0x103990) ∧ (pos.toNat = 0 → eip = 0x103afd) := by
    by_cases hp0 : pos.toNat = 0
    · have X := lc2x (icAdd ic1 {cnt}) (icAdd_lt hic1 (by decide)) {mem} L (hS.size_eq {C}.pres.1) {reg['eax']} {reg['ecx']}
        {reg['edx']} {reg['ebx']} {reg['ebp']} (UInt32.add pos 4294967295) {reg['edi']} (addF 4 pos 4294967295 0).2 bitv
        (Branch.cfB_addm1_zero pos hp0) lb
      simp only [icAdd_add] at X
      exact ⟨_, X, fun h => absurd hp0 h, fun _ => rfl⟩
    · have X := lc2t (icAdd ic1 {cnt}) (icAdd_lt hic1 (by decide)) {mem} L (hS.size_eq {C}.pres.1) {reg['eax']} {reg['ecx']}
        {reg['edx']} {reg['ebx']} {reg['ebp']} (UInt32.add pos 4294967295) {reg['edi']} (addF 4 pos 4294967295 0).2 bitv
        (Branch.cfB_addm1_ne pos hp0) lb
      simp only [icAdd_add] at X
      exact ⟨_, X, fun _ => rfl, fun h => absurd h hp0⟩
  obtain ⟨eip, XF, he1, he2⟩ := hfin""")
    cnt += 2
    # outputs
    x2, z2, x3, z3 = buf[88], buf[208], buf[128], buf[48]
    a(f"""  have hBB : mulp (subp xa xb) (subp xa xb) < p := Nat.mod_lt _ (by have := p_gt; omega)
  refine ⟨{mem}, bitv, _, _, _, _, _, _, {reg['eax']}, {reg['ecx']}, {reg['edx']}, {reg['ebx']}, {reg['ebp']},
    (addF 4 pos 4294967295 0).2, eip, ?_, he1, he2, {C}, hb01, hbit, {z3[1]}, {x2[1]}, {x3[1]},
    {z2[1]}, ?_, ?_, ?_, ?_⟩
  · rw [← icAdd_add, hI]
    exact (({RR}.trans AE).trans L1).trans XF
  all_goals rw [ladderStep_eq, ← hbit, ← ha2, ← hb2, ← hc2, ← hd2]
  · exact {x2[2]}
  · show Rep _ (mulp (subp (mulp (addp xa xb) (addp xa xb)) (mulp (subp xa xb) (subp xa xb)))
      (addp (mulp (addp xa xb) (addp xa xb)) (mulp a24 (subp (mulp (addp xa xb) (addp xa xb))
        (mulp (subp xa xb) (subp xa xb))))))
    rw [← a24_identity _ _ hBB]
    exact {z2[2]}
  · exact {x3[2]}
  · exact {z3[2]}

end Solutions.OpensslX25519.I
""")
    return out, cnt


if __name__ == '__main__':
    ps, calls = pieces()
    body, K = main_proof(calls)
    txt = HDR.replace('{K}', str(K)) + '\n'.join(body)
    open(os.path.join(D, 'I', 'LadIter.lean'), 'w').write(txt)
    print('K', K)
