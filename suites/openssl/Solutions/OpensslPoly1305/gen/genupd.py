"""Poly1305_Update (0x1000e0): run pieces and composites of its straight segments (between the
branches and the calls of poly1305_blocks / memcpy).  Stack region `[U, U + 272)` (entry stack
pointer `U + 256`: return address, ctx, inp, len), context `[C, C + 236)`.

    python3 genupd.py      (from this directory) writes ../UpdRun.lean, ../UpdC.lean
"""
import os
from psym import Seg, V
from pchain import chain

D = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
HDR = """import Solutions.OpensslPoly1305.{imp}
/-!
# {what}

Generated by `gen/genupd.py` (`gen/psym.py`, `gen/pchain.py`): stack region `[U, U + 272)`, context
`[C, C + 236)`.
-/
namespace Solutions.OpensslPoly1305
open X86 Ssl Solutions.Logic Solutions.Exec Ssl.OpensslPoly1305 Solutions.Exec.Mul Solutions.Exec.Fast
open Solutions.OpensslPoly1305.Cbv Solutions.Logic.Cmp

attribute [local cbv_opaque] Image.bytes
set_option maxRecDepth 100000
set_option maxHeartbeats 0
set_option cbv.maxSteps 50000000
set_option exec.addrSub true
set_option autoImplicit false
"""
ARGS = {256: V('ret'), 260: V('C'), 264: V('inp'), 268: V('len')}
SAVED = {252: V('ebp0'), 248: V('ebx0'), 244: V('edi0'), 240: V('esi0'), 236: V('a0')}


def R(**kw):
    r = {'eax': V('a1'), 'ecx': V('c1'), 'edx': V('d1'), 'ebx': V('b1'), 'ebp': V('p1'), 'esi': V('s1'),
         'edi': V('i1')}
    for k, v in kw.items():
        r[k] = v
    return r


# (name, regs, esp, eip, slots, cslots, branches, stop, outs_U, outs_C)
SEGS = [
    ('upd_a0', R(eax=V('a0'), ecx=V('c0'), edx=V('d0'), ebx=V('ebx0'), ebp=V('ebp0'), esi=V('esi0'), edi=V('edi0')),
     256, 0x1000e0, ARGS, {224: V('num')}, {0x1000f9: (True, 'num.toNat = 0')}, 0x100124),
    ('upd_a1', R(eax=V('a0'), ecx=V('c0'), edx=V('d0'), ebx=V('ebx0'), ebp=V('ebp0'), esi=V('esi0'), edi=V('edi0')),
     256, 0x1000e0, ARGS, {224: V('num')}, {0x1000f9: (False, 'num.toNat ≠ 0')}, 0x1000fb),
    ('upd_b0', R(edx=V('len'), esi=V('C'), edi=V('inp')), 236, 0x100124, {**ARGS, **SAVED}, {},
     {0x10012e: (True, 'len.toNat < 16')}, 0x100144),
    ('upd_b1', R(edx=V('len'), esi=V('C'), edi=V('inp')), 236, 0x100124, {**ARGS, **SAVED}, {},
     {0x10012e: (False, '16 ≤ len.toNat')}, 0x100130),
    ('upd_c', R(ebp=V('l'), esi=V('C'), edi=V('p')), 236, 0x100130, {**ARGS, **SAVED}, {}, {}, 0x1001b0),
    ('upd_d', R(ebp=V('l'), esi=V('C'), edi=V('p')), 228, 0x10013f, {**ARGS, **SAVED}, {}, {}, 0x100144),
    ('upd_e0', R(ebx=V('t'), esi=V('C'), edi=V('p')), 236, 0x100144, {**ARGS, **SAVED}, {},
     {0x100146: (True, 't.toNat = 0')}, None),
    ('upd_e1', R(ebx=V('t'), esi=V('C'), edi=V('p')), 236, 0x100144, {**ARGS, **SAVED}, {},
     {0x100146: (False, 't.toNat ≠ 0')}, 0x1005a0),
    ('upd_f', R(ebx=V('t'), esi=V('C'), edi=V('p')), 224, 0x100156, {**ARGS, **SAVED}, {}, {}, None),
    ('upd_g0', R(edx=V('len'), ebx=V('num'), esi=V('C'), edi=V('inp')), 236, 0x1000fb, {**ARGS, **SAVED}, {},
     {0x10010f: (False, 'len.toNat < 16 - num.toNat ∧ num.toNat < 16')}, 0x1005a0),
    ('upd_g1', R(edx=V('len'), ebx=V('num'), esi=V('C'), edi=V('inp')), 236, 0x1000fb, {**ARGS, **SAVED}, {},
     {0x10010f: (True, '16 - num.toNat ≤ len.toNat ∧ num.toNat < 16')}, 0x1005a0),
    ('upd_h', R(ebx=V('num'), esi=V('C'), edi=V('len')), 224, 0x10011d, {**ARGS, **SAVED}, {}, {}, None),
    ('upd_i', R(ebx=V('C'), esi=V('rem'), edi=V('inp'), ebp=V('l')), 224, 0x10016e,
     {**ARGS, **SAVED, 236: V('dp')}, {}, {}, 0x1001b0),
    ('upd_j0', R(ebx=V('C'), esi=V('rem'), edi=V('inp'), ebp=V('l')), 228, 0x10017f,
     {**ARGS, **SAVED, 236: V('dp')}, {}, {0x10018e: (True, '16 ≤ l.toNat')}, 0x100130),
    ('upd_j1', R(ebx=V('C'), esi=V('rem'), edi=V('inp'), ebp=V('l')), 228, 0x10017f,
     {**ARGS, **SAVED, 236: V('dp')}, {}, {0x10018e: (False, 'l.toNat < 16')}, 0x100144),
]

# what the values the segments compute are (stated after the run)
EXTRA = {
    'upd_b0': 'v1 = UInt32.land len 15',
    'upd_b1': 'v1 = UInt32.land len 15',
    'upd_c': 'v1 = UInt32.land l 4294967280',
    'upd_d': 'v2 = (addF 4 p l 0).1',
    'upd_g0': 'v5 = UInt32.add (UInt32.add C num) 208 ∧ v3 = (subF 4 len (subF 4 16 num 0).1 0).1',
    'upd_g1': 'v5 = UInt32.add (UInt32.add C num) 208 ∧ v3 = (subF 4 len (subF 4 16 num 0).1 0).1 ∧ '
              'v1 = (subF 4 16 num 0).1',
    'upd_h': 'v2 = (addF 4 num len 0).1',
    'upd_j0': 'v2 = (addF 4 inp rem 0).1 ∧ v4 = UInt32.land l 15',
    'upd_j1': 'v2 = (addF 4 inp rem 0).1 ∧ v4 = UInt32.land l 15',
}

pieces_txt, chains_txt = [], []
summary = []
for (name, regs, esp, eip, slots, cslots, br, stop) in SEGS:
    s = Seg(name, dict(regs), esp, eip, 'g0', 272, 236, 236, slots=dict(slots), cslots=dict(cslots))
    s.branch = dict(br)
    ps = s.run(stop)
    names = ['%s_%d' % (name, j) for j in range(len(ps))]
    pieces_txt += [s.lemma(p, n) for p, n in zip(ps, names)]
    # keep every stack word the segment ends knowing, and the context words it loads or stores
    outsU = sorted(o for o in s.slots if s.slots[o] is not None)
    outsC = sorted(s.cslots)
    txt, _, junk = chain(s, ps, name, (regs, esp, eip, 'g0', 0), sorted(slots.items()), sorted(cslots.items()),
                         [], outsU, outsC, names, explicit_C=True,
                         extra_concl=EXTRA.get(name))
    chains_txt.append(txt)
    summary.append((name, len(ps), s.ic, s.eip, s.esp))
open(os.path.join(D, 'UpdRun.lean'), 'w').write(
    HDR.format(imp='Mem', what='Run pieces of `Poly1305_Update`') + "".join(pieces_txt) +
    "\nend Solutions.OpensslPoly1305\n")
open(os.path.join(D, 'UpdC.lean'), 'w').write(
    HDR.format(imp='UpdRun', what='The straight segments of `Poly1305_Update`') + "".join(chains_txt) +
    "\nend Solutions.OpensslPoly1305\n")
for x in summary:
    print(x)
