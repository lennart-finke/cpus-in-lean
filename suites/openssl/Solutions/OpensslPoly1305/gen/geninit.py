"""Poly1305_Init (0x100010, with U8TOU32 and poly1305_init inlined): run pieces and the composite.

Stack region `[U, U + 268)` (entry stack pointer `U + 256`: return address, ctx, key), context
`[C, C + 236)`, key `[keyp, keyp + 32)` read-only.

    python3 geninit.py      (from this directory) writes ../InitRun.lean, ../InitC.lean
"""
import os
from psym import Seg, V
from pchain import chain

D = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
HDR = """import Solutions.OpensslPoly1305.Mem
/-!
# {what}

Generated by `gen/geninit.py` (`gen/psym.py`, `gen/pchain.py`): stack region `[U, U + 268)`, context
`[C, C + 236)`, key `[keyp, keyp + 32)`.
-/
namespace Solutions.OpensslPoly1305
open X86 Ssl Solutions.Logic Solutions.Exec Ssl.OpensslPoly1305 Solutions.Exec.Mul Solutions.Exec.Fast
open Solutions.OpensslPoly1305.Cbv Solutions.Logic.Cmp

attribute [local cbv_opaque] Image.bytes
set_option maxRecDepth 100000
set_option maxHeartbeats 0
set_option cbv.maxSteps 50000000
set_option exec.addrSub true
set_option autoImplicit false
"""
FACTS = [
    ('hkey', 'keyp.toNat + 32 ≤ N.get.size', ['keyp']),
    ('hkeyU', 'keyp.toNat + 32 ≤ U.toNat ∨ U.toNat + 268 ≤ keyp.toNat', ['keyp', 'U']),
    ('hkeyC', 'keyp.toNat + 32 ≤ C.toNat ∨ C.toNat + 236 ≤ keyp.toNat', ['keyp', 'C']),
]
regs = {'eax': V('a0'), 'ecx': V('c0'), 'edx': V('d0'), 'ebx': V('ebx0'), 'ebp': V('ebp0'),
        'esi': V('esi0'), 'edi': V('edi0')}
initU = [(256, V('ret')), (260, V('C')), (264, V('keyp'))]
s = Seg('ini', dict(regs), 256, 0x100010, 'g0', 268, 236, 236, slots=dict(initU), facts=FACTS)
s.allow_lit = True
ps = s.run(None)
names = ['ini_p%d' % j for j in range(len(ps))]
txt = HDR.format(what='Run pieces of `Poly1305_Init`') + "".join(s.lemma(p, n) for p, n in zip(ps, names)) + \
    "\nend Solutions.OpensslPoly1305\n"
open(os.path.join(D, 'InitRun.lean'), 'w').write(txt)
outsC = [0, 4, 8, 12, 16, 20, 24, 28, 32, 192, 196, 200, 204, 224]
from pchain import expand
rv = [s.cslots[o].term() for o in (20, 24, 28, 32)]
ex = " ∧ ".join(f"{v} = {expand(s.defs[v], s.defs)}" for v in rv)
ctxt, ins, junk = chain(s, ps, 'ini_run', (regs, 256, 0x100010, 'g0', 0), initU, [], [('keyp', 32)],
                        [256, 260, 264], outsC, names, extra_concl=ex)
hdr = HDR.format(what='`Poly1305_Init` as one run').replace('import Solutions.OpensslPoly1305.Mem',
                                                             'import Solutions.OpensslPoly1305.InitRun')
open(os.path.join(D, 'InitC.lean'), 'w').write(hdr + ctxt + "\nend Solutions.OpensslPoly1305\n")
print(len(ps), 'pieces', s.ic, 'instructions; outputs', junk)
print({o: s.cslots[o].term() for o in outsC})
