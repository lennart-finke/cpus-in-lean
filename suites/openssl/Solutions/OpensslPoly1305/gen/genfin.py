"""Poly1305_Final (0x100460): run pieces and composites of its straight segments, with poly1305_emit
(U32TO8 inlined) and OPENSSL_cleanse up to the indirect call of memset.  Stack region `[U, U + 268)`
(entry stack pointer `U + 256`: return address, ctx, mac).  The data region is the context `[C, C + 236)`
("ctx mode"), the pad bytes `[C + 208, C + 224)` region `D` with nothing stored through it ("pad mode", the
byte stores are separate lemmas), or the tag `[mac, mac + 16)` ("mac mode", the context read-only).

    python3 genfin.py      (from this directory) writes ../FinRun.lean, ../FinC.lean
"""
import os
from psym import Seg, V
from pchain import chain, expand

D = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
HDR = """import Solutions.OpensslPoly1305.{imp}
/-!
# {what}

Generated by `gen/genfin.py` (`gen/psym.py`, `gen/pchain.py`): stack region `[U, U + 268)`; data region
the context `C` (236 bytes), the pad region `D` (16 bytes, no stores) or the tag `mac` (16 bytes).
-/
namespace Solutions.OpensslPoly1305
open X86 Ssl Solutions.Logic Solutions.Exec Ssl.OpensslPoly1305 Solutions.Exec.Mul Solutions.Exec.Fast
open Solutions.OpensslPoly1305.Cbv Solutions.Logic.Cmp

attribute [local cbv_opaque] Image.bytes
set_option maxRecDepth 100000
set_option maxHeartbeats 0
set_option cbv.maxSteps 50000000
set_option exec.addrSub true
set_option autoImplicit false
"""
ARGS = {256: V('ret'), 260: V('C'), 264: V('mac')}
SAVED = {248: V('esi0'), 252: V('edi0')}


def R(**kw):
    r = {'eax': V('a1'), 'ecx': V('c1'), 'edx': V('d1'), 'ebx': V('ebx0'), 'ebp': V('ebp0'), 'esi': V('C'),
         'edi': V('mac')}
    for k, v in kw.items():
        r[k] = v
    return r


R0 = dict(eax=V('a0'), ecx=V('c0'), edx=V('d0'), ebx=V('ebx0'), ebp=V('ebp0'), esi=V('esi0'), edi=V('edi0'))
CTX = ('C', 236, 236)
PAD = ('D', 16, 0)
MAC = ('mac', 16, 16)
# (name, mode, regs, esp, eip, slots, cslots, branches, stop, exts, allow_lit, extra)
SEGS = [
    ('fin_a0', CTX, R0, 256, 0x100460, ARGS, {224: V('num')}, {0x100472: (True, 'num.toNat = 0')}, 0x1004ac,
     [], False, None),
    ('fin_a1', CTX, R0, 256, 0x100460, ARGS, {224: V('num')}, {0x100472: (False, 'num.toNat ≠ 0')}, 0x10047a,
     [], False, None),
    ('fin_b0', PAD, R(eax=V('num')), 248, 0x100482, {**ARGS, **SAVED}, {},
     {0x100488: (True, '15 < (UInt32.add num 1).toNat')}, 0x10049e, [], False, None),
    ('fin_b1', PAD, R(eax=V('num')), 248, 0x100482, {**ARGS, **SAVED}, {},
     {0x100488: (False, '(UInt32.add num 1).toNat < 15')}, 0x100490, [], False, None),
    ('fin_b2', PAD, R(eax=V('num')), 248, 0x100482, {**ARGS, **SAVED}, {},
     {0x100488: (False, '(UInt32.add num 1).toNat = 15')}, 0x100490, [], False, None),
    ('fin_c0', PAD, R(eax=V('i')), 248, 0x100498, {**ARGS, **SAVED}, {},
     {0x10049c: (True, '(UInt32.add i 1).toNat ≠ 15')}, 0x100490, [], False, None),
    ('fin_c1', PAD, R(eax=V('i')), 248, 0x100498, {**ARGS, **SAVED}, {},
     {0x10049c: (False, '(UInt32.add i 1).toNat = 15')}, 0x10049e, [], False, None),
    ('fin_d', CTX, R(), 248, 0x10049e, {**ARGS, **SAVED}, {}, {}, 0x1001b0, [], False, None),
    ('fin_e', CTX, R(), 240, 0x1004a9, {**ARGS, **SAVED}, {}, {}, 0x1004ac, [], False, None),
    ('fin_f', CTX, R(), 248, 0x1004ac, {**ARGS, **SAVED}, {}, {}, 0x1004d0, [], False, None),
    ('fin_g', MAC, R(eax=V('sp'), ecx=V('C'), edx=V('mac')), 240, 0x1004d0,
     {**ARGS, **SAVED, 240: V(None, 0x1004bc), 244: V('sp')}, {}, {}, 0x1004bc, [('C', 20), ('sp', 16)], True,
     'emit'),
    ('fin_h', MAC, R(), 244, 0x1004bc, {**ARGS, **SAVED, 244: V('sp')}, {}, {}, 0x1005d0, [], True, None),
    ('fin_i', MAC, R(), 224, 0x100591, {**ARGS, **SAVED, 236: V(None, 0x1004ca), 240: V('C'), 244: V(None, 236)},
     {}, {}, None, [], True, None),
]

pieces_txt, chains_txt = [], []
for (name, mode, regs, esp, eip, slots, cslots, br, stop, exts, allow, extra) in SEGS:
    Cn, nC, mC = mode
    if Cn != 'C':
        # the context pointer is an ordinary (lower-case) variable when it is not the data region
        ren = lambda v: V('ctx', v.off) if v.base == 'C' else v
        regs = {k: ren(v) for k, v in regs.items()}
        slots = {k: ren(v) for k, v in slots.items()}
        exts = [('ctx' if p == 'C' else p, L) for (p, L) in exts]
    facts = []
    for (pn, L) in exts:
        facts += [(f'h{pn}', f'{pn}.toNat + {L} ≤ N.get.size', [pn]),
                  (f'h{pn}U', f'{pn}.toNat + {L} ≤ U.toNat ∨ U.toNat + 268 ≤ {pn}.toNat', [pn, 'U']),
                  (f'h{pn}C', f'{pn}.toNat + {L} ≤ {Cn}.toNat ∨ {Cn}.toNat + {nC} ≤ {pn}.toNat', [pn, Cn])]
    if name == 'fin_h':
        # `movl 0x1005fc, %eax` reads the image
        facts.append(('himg', '0x100000 + 1536 ≤ N.get.size', []))
        s_img = True
    else:
        s_img = False
    s = Seg(name, dict(regs), esp, eip, 'g0', 268, nC, mC, Cname=Cn, slots=dict(slots), cslots=dict(cslots),
            facts=facts)
    s.branch = dict(br)
    s.img_load = s_img
    if allow:
        s.allow_lit = True
    ps = s.run(stop)
    names = ['%s_%d' % (name, j) for j in range(len(ps))]
    pieces_txt += [s.lemma(p, n) for p, n in zip(ps, names)]
    outsU = sorted(o for o in s.slots if s.slots[o] is not None)
    outsC = sorted(s.cslots)
    ex = None
    if extra == 'emit':
        ws = [s.cslots[o].term() for o in (0, 4, 8, 12)]
        print('emit words', ws)
        for w in ws:
            print(w, '=', expand(s.defs[w], s.defs) if w in s.defs else w)
        ld = {key: v.term() for p in ps for (kind, key, v) in p['loads'] if kind == 'ext'}
        EMIT_IN = [ld[k] for k in ('ctx', '(UInt32.add ctx 4)', '(UInt32.add ctx 8)', '(UInt32.add ctx 12)',
                                   '(UInt32.add ctx 16)', 'sp', '(UInt32.add sp 4)', '(UInt32.add sp 8)',
                                   '(UInt32.add sp 12)')]
        ex = f"({ws[0]}, {ws[1]}, {ws[2]}, {ws[3]}) = emitW {' '.join(EMIT_IN)}"
    elif name in ('fin_c0', 'fin_c1'):
        ex = 'v1 = UInt32.add i 1'
    txt, _, junk = chain(s, ps, name, (regs, esp, eip, 'g0', 0), sorted(slots.items()), sorted(cslots.items()),
                         exts, outsU, outsC, names, explicit_C=True, extra_concl=ex)
    chains_txt.append(txt)
    print(name, len(ps), 'pieces', s.ic, 'ins; eip', s.eip, 'esp', s.esp, 'junk', junk)
open(os.path.join(D, 'FinRun.lean'), 'w').write(
    HDR.format(imp='Mem', what='Run pieces of `Poly1305_Final`') + "".join(pieces_txt) +
    "\nend Solutions.OpensslPoly1305\n")
open(os.path.join(D, 'FinC.lean'), 'w').write(
    HDR.format(imp='FinImg', what='The straight segments of `Poly1305_Final`') + "".join(chains_txt) +
    "\nend Solutions.OpensslPoly1305\n")
