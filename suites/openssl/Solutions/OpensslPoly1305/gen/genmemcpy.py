"""memcpy (0x1005a0): run pieces of the prologue (both ways of `je`), the loop step after the byte
copy (`incl; cmpl; jne` both ways) and the epilogue.  The stack region is `[U, U + 24)` (two saved
registers, the return address, three arguments), the data region `[D, D + 16)`.

    python3 genmemcpy.py      (from this directory) writes ../McRun.lean
"""
import os
from psym import Seg, V

D = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
HDR = """import Solutions.OpensslPoly1305.Mem
/-!
# Run pieces of `memcpy`

Generated by `gen/genmemcpy.py` (`gen/psym.py`): stack region `[U, U + 24)`, destination region
`[D, D + 16)`.
-/
namespace Solutions.OpensslPoly1305
open X86 Ssl Solutions.Logic Solutions.Exec Ssl.OpensslPoly1305 Solutions.Exec.Mul Solutions.Exec.Fast
open Solutions.OpensslPoly1305.Cbv Solutions.Logic.Cmp

attribute [local cbv_opaque] Image.bytes
set_option maxRecDepth 100000
set_option maxHeartbeats 0
set_option cbv.maxSteps 50000000
set_option exec.addrSub true
set_option autoImplicit false
"""
SLOTS = {8: V('ret'), 12: V('dst'), 16: V('src'), 20: V('n')}


def seg(pre, regs, esp, eip, slots):
    return Seg(pre, regs, esp, eip, 'g0', 24, 16, 0, Cname='D', slots=slots)


out = []
# prologue, n = 0
s = seg('mc_z', {'eax': V('a0'), 'ecx': V('c0'), 'edx': V('d0'), 'ebx': V('ebx0'), 'ebp': V('ebp0'),
                 'esi': V('esi0'), 'edi': V('edi0')}, 8, 0x1005a0, SLOTS)
s.branch[0x1005ac] = (True, 'n.toNat = 0')
for j, p in enumerate(s.run(0x1005cc)):
    out.append(s.lemma(p, 'mc_z%d' % j))
# prologue, n ≠ 0
s = seg('mc_p', {'eax': V('a0'), 'ecx': V('c0'), 'edx': V('d0'), 'ebx': V('ebx0'), 'ebp': V('ebp0'),
                 'esi': V('esi0'), 'edi': V('edi0')}, 8, 0x1005a0, SLOTS)
s.branch[0x1005ac] = (False, 'n.toNat ≠ 0')
for j, p in enumerate(s.run(0x1005c0)):
    out.append(s.lemma(p, 'mc_p%d' % j))
# the loop step after the copy of byte i
for taken in (True, False):
    s = seg('mc_s', {'eax': V('dst'), 'ecx': V('n'), 'edx': V('src'), 'ebx': V('b'), 'ebp': V('ebp0'),
                     'esi': V('i'), 'edi': V('edi0')}, 0, 0x1005c7, {})
    s.flag = 'g0'
    s.branch[0x1005ca] = (taken, '(UInt32.add i 1).toNat ≠ n.toNat' if taken else '(UInt32.add i 1).toNat = n.toNat')
    for j, p in enumerate(s.run(0x1005c0 if taken else 0x1005cc)):
        out.append(s.lemma(p, 'mc_st' if taken else 'mc_sn'))
# epilogue
s = seg('mc_e', {'eax': V('a0'), 'ecx': V('c0'), 'edx': V('d0'), 'ebx': V('b'), 'ebp': V('ebp0'),
                 'esi': V('i'), 'edi': V('edi0')}, 0, 0x1005cc, {0: V('esi0'), 4: V('ebx0'), 8: V('ret')})
for j, p in enumerate(s.run(None)):
    out.append(s.lemma(p, 'mc_e%d' % j))
open(os.path.join(D, 'McRun.lean'), 'w').write(HDR + "".join(out) + "\nend Solutions.OpensslPoly1305\n")
print(len(out), 'pieces')
