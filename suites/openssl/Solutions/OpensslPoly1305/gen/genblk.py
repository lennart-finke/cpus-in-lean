"""poly1305_blocks: run pieces of the prologue, one loop iteration and the epilogue.

    python3 genblk.py      (from this directory) writes ../BlkRun*.lean
"""
import os, sys
from psym import Seg, V, INS

D = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')

HDR = """import Solutions.OpensslPoly1305.Mem
/-!
# Run pieces of `poly1305_blocks` ({what})

Generated by `gen/genblk.py` (`gen/psym.py`): each piece runs a few instructions by `cbv` from a
memory `N` described by `MemOK` (stack region `[U, U + 116)`, context `[C, C + 236)` of which the
first 20 bytes may be written), and states the values it computes as single-operation equations.
-/
namespace Solutions.OpensslPoly1305
open X86 Ssl Solutions.Logic Solutions.Exec Ssl.OpensslPoly1305 Solutions.Exec.Mul Solutions.Exec.Fast
open Solutions.OpensslPoly1305.Cbv Solutions.Logic.Cmp

attribute [local cbv_opaque] Image.bytes
set_option maxRecDepth 100000
set_option maxHeartbeats 0
set_option cbv.maxSteps 50000000
set_option exec.addrSub true
set_option autoImplicit false
"""


def facts_common():
    return [
        ('hinp', 'inp.toNat + 16 ≤ N.get.size', ['inp']),
        ('hinpU', 'inp.toNat + 16 ≤ U.toNat ∨ U.toNat + 116 ≤ inp.toNat', ['inp', 'U']),
    ]


def prologue():
    regs = {'eax': V('a0'), 'ecx': V('C'), 'edx': V('inp'), 'ebx': V('ebx0'), 'ebp': V('ebp0'),
            'esi': V('esi0'), 'edi': V('edi0')}
    s = Seg('blk_pro', regs, 104, 0x1001b0, 'g0', 116, 236, 20,
            slots={104: V('ret'), 108: V('len'), 112: V('pad')},
            cslots={0: V('h0'), 4: V('h1'), 8: V('h2'), 12: V('h3'), 16: V('h4'), 20: V('r0'), 24: V('r1'),
                    28: V('r2'), 32: V('r3')},
            facts=facts_common())
    ps = s.run(0x100220)
    return s, ps


BODY_SLOTS = {4: V('h0'), 8: V('h2'), 12: V('h1'), 24: V('r0'), 28: V('s3'), 36: V('s2'), 40: V('r1'),
              44: V('s1'), 48: V('r2'), 52: V('C'), 56: V('r3'), 88: V('esi0'), 92: V('edi0'), 96: V('ebx0'), 100: V('ebp0'), 104: V('ret'), 108: V('len0'), 112: V('pad')}


def body():
    regs = {'eax': V('len'), 'ecx': V('c0'), 'edx': V('inp'), 'ebx': V('h3'), 'ebp': V('b0'),
            'esi': V('h4'), 'edi': V('d0')}
    s = Seg('blk_b', regs, 4, 0x100220, 'gf', 116, 236, 20, slots=BODY_SLOTS, facts=facts_common())
    ps = s.run(0x100424)
    return s, ps


def branch(taken):
    regs = {'eax': V('len'), 'ecx': V('c0'), 'edx': V('inp'), 'ebx': V('h3'), 'ebp': V('b0'),
            'esi': V('h4'), 'edi': V('d0')}
    s = Seg('blk_j', regs, 4, 0x100424, 'gf', 116, 236, 20, slots=BODY_SLOTS)
    s.branch[0x100427] = (taken, '15 < len.toNat' if taken else 'len.toNat = 0')
    ps = s.run(0x100220 if taken else 0x10042d)
    return s, ps


def epilogue():
    regs = {'eax': V('a0'), 'ecx': V('c0'), 'edx': V('inp'), 'ebx': V('h3'), 'ebp': V('b0'),
            'esi': V('h4'), 'edi': V('d0')}
    s = Seg('blk_e', regs, 4, 0x10042d, 'gf', 116, 236, 20, slots=BODY_SLOTS)
    ps = s.run(None)
    return s, ps


def write(name, what, items):
    txt = HDR.format(what=what)
    for (s, p, nm) in items:
        txt += s.lemma(p, nm)
    txt += "\nend Solutions.OpensslPoly1305\n"
    open(os.path.join(D, name + '.lean'), 'w').write(txt)


if __name__ == '__main__':
    sb, pb = body()
    print(len(pb), 'body pieces; end regs', {r: v.term() for r, v in sb.regs.items()}, 'esp', sb.esp, 'ic', sb.ic)
    print('slots', {k: v.term() for k, v in sorted(sb.slots.items())})
    PER = 6
    for f in range(0, len(pb), PER):
        write('BlkBody%d' % (f // PER + 1), 'loop body, pieces %d-%d' % (f, min(f + PER, len(pb)) - 1),
              [(sb, p, 'blk_b%d' % (f + j)) for j, p in enumerate(pb[f:f + PER])])
    st, pt = branch(True)
    sn, pn = branch(False)
    se, pe = epilogue()
    print('epilogue', len(pe), 'pieces', se.ic)
    write('BlkEnds', 'loop branch and epilogue', [(st, pt[0], 'blk_jt'), (sn, pn[0], 'blk_jn')] +
          [(se, p, 'blk_e%d' % j) for j, p in enumerate(pe)])
    # the function of one block and the composite of the body
    from pchain import chain, names_in
    free = []
    for nm, t in sb.defs.items():
        for x in names_in(t):
            if x not in sb.defs and x not in free:
                free.append(x)
    outs = [sb.slots[4].term(), sb.slots[12].term(), sb.slots[8].term(), sb.regs['ebx'].term(), sb.regs['esi'].term()]
    fdef = "\n/-- One block of `poly1305_blocks` as the code computes it (`h0 … h4` after the block). -/\n"
    fdef += f"def blkF ({' '.join(free)} : UInt32) : UInt32 × UInt32 × UInt32 × UInt32 × UInt32 :=\n"
    for nm, t in sb.defs.items():
        fdef += f"  let {nm} := {t}\n"
    fdef += f"  ({', '.join(outs)})\n"
    ins = ({'eax': V('len'), 'ecx': V('c0'), 'edx': V('inp'), 'ebx': V('h3'), 'ebp': V('b0'),
            'esi': V('h4'), 'edi': V('d0')}, 4, 0x100220, 'gf', 0)
    initU = sorted(BODY_SLOTS.items())
    txt, inputs, junk = chain(sb, pb, 'blk_it', ins, initU, [(20, V('r0')), (24, V('r1')), (28, V('r2')), (32, V('r3'))], [('inp', 16)],
                              [4, 8, 12] + [o for o, _ in initU if o not in (4, 8, 12)], [20, 24, 28, 32],
                              ['blk_b%d' % j for j in range(len(pb))],
                              extra_concl=f"({', '.join(outs)}) = blkF {' '.join(free)} ∧ {sb.regs['eax'].term()} = {sb.defs[sb.regs['eax'].term()]} ∧ {sb.regs['edx'].term()} = {sb.defs[sb.regs['edx'].term()]}")
    hdr = HDR.format(what='one iteration of the loop').replace('import Solutions.OpensslPoly1305.Mem',
        '\n'.join('import Solutions.OpensslPoly1305.BlkBody%d' % (k + 1) for k in range((len(pb) + PER - 1) // PER)))
    open(os.path.join(D, 'BlkIter.lean'), 'w').write(hdr + fdef + txt + "\nend Solutions.OpensslPoly1305\n")
    print('blkF params', free)
    # prologue and epilogue composites
    spro, ppro = prologue()
    write('BlkPro', 'prologue', [(spro, q, 'blk_pro%d' % j) for j, q in enumerate(ppro)])
    pins = ({'eax': V('a0'), 'ecx': V('C'), 'edx': V('inp'), 'ebx': V('ebx0'), 'ebp': V('ebp0'),
             'esi': V('esi0'), 'edi': V('edi0')}, 104, 0x1001b0, 'g0', 0)
    initC = [(0, V('h0')), (4, V('h1')), (8, V('h2')), (12, V('h3')), (16, V('h4')), (20, V('r0')),
             (24, V('r1')), (28, V('r2')), (32, V('r3'))]
    sl = spro.slots
    sv = [sl[44].term(), sl[36].term(), sl[28].term()]
    from pchain import expand
    ex = " ∧ ".join(f"{v} = {expand(spro.defs[v], spro.defs)}" for v in sv)
    txtp, _, _ = chain(spro, ppro, 'blk_pro', pins, [(104, V('ret')), (108, V('len')), (112, V('pad'))], initC, [],
                       [o for o, _ in initU], [o for o, _ in initC], ['blk_pro%d' % j for j in range(len(ppro))],
                       extra_concl=ex)
    st_, pt_ = branch(True)
    sn_, pn_ = branch(False)
    se, pe = epilogue()
    eins = ({'eax': V('a0'), 'ecx': V('c0'), 'edx': V('inp'), 'ebx': V('h3'), 'ebp': V('b0'),
             'esi': V('h4'), 'edi': V('d0')}, 4, 0x10042d, 'gf', 0)
    initE = [(o, v) for o, v in initU]
    txte, _, _ = chain(se, pe, 'blk_epi', eins, initE, [(20, V('r0')), (24, V('r1')), (28, V('r2')), (32, V('r3'))], [],
                       [], [0, 4, 8, 12, 16, 20, 24, 28, 32], ['blk_e%d' % j for j in range(len(pe))])
    hdr2 = HDR.format(what='prologue and epilogue composites').replace(
        'import Solutions.OpensslPoly1305.Mem', 'import Solutions.OpensslPoly1305.BlkPro\nimport Solutions.OpensslPoly1305.BlkEnds')
    open(os.path.join(D, 'BlkPE.lean'), 'w').write(hdr2 + txtp + txte + "\nend Solutions.OpensslPoly1305\n")
    print('outs', outs, 'junk', junk)

    s, ps = prologue()
    txt = HDR.format(what='prologue')
    for j, p in enumerate(ps):
        txt += s.lemma(p, f"blk_pro{j}")
    txt += "\nend Solutions.OpensslPoly1305\n"
    open(os.path.join(D, 'BlkPro.lean'), 'w').write(txt)
    print(len(ps), 'pieces; end regs', {r: v.term() for r, v in s.regs.items()}, 'esp', s.esp, 'ic', s.ic)
    print('slots', {k: v.term() for k, v in sorted(s.slots.items())})
