"""memset (0x1005d0): run pieces of the prologue (both ways of `je`), the loop step after the byte
store (`incl; decl; jne` both ways) and the epilogue.  Stack region `[U, U + 20)` (the saved esi,
the return address, three arguments), destination region `[D, D + 236)`.

    python3 genmemset.py      (from this directory) writes ../MsRun.lean
"""
import os
from psym import Seg, V

D = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
HDR = """import Solutions.OpensslPoly1305.Mem
/-!
# Run pieces of `memset`

Generated by `gen/genmemset.py` (`gen/psym.py`): stack region `[U, U + 20)`, destination region
`[D, D + 236)`.
-/
namespace Solutions.OpensslPoly1305
open X86 Ssl Solutions.Logic Solutions.Exec Ssl.OpensslPoly1305 Solutions.Exec.Mul Solutions.Exec.Fast
open Solutions.OpensslPoly1305.Cbv Solutions.Logic.Cmp

attribute [local cbv_opaque] Image.bytes
set_option maxRecDepth 100000
set_option maxHeartbeats 0
set_option cbv.maxSteps 50000000
set_option exec.addrSub true
set_option autoImplicit false
"""
SLOTS = {4: V('ret'), 8: V('dst'), 12: V('cv'), 16: V('n')}


def seg(pre, regs, esp, eip, slots):
    return Seg(pre, regs, esp, eip, 'g0', 20, 236, 0, Cname='D', slots=slots)


R0 = {'eax': V('a0'), 'ecx': V('c0'), 'edx': V('d0'), 'ebx': V('ebx0'), 'ebp': V('ebp0'), 'esi': V('esi0'),
      'edi': V('edi0')}
out = []
s = seg('ms_z', dict(R0), 4, 0x1005d0, SLOTS)
s.branch[0x1005db] = (True, 'n.toNat = 0')
for j, p in enumerate(s.run(0x1005f6)):
    out.append(s.lemma(p, 'ms_z%d' % j))
s = seg('ms_p', dict(R0), 4, 0x1005d0, SLOTS)
s.branch[0x1005db] = (False, 'n.toNat ≠ 0')
for j, p in enumerate(s.run(0x1005f0)):
    out.append(s.lemma(p, 'ms_p%d' % j))
for taken in (True, False):
    s = seg('ms_s', {'eax': V('a0'), 'ecx': V('k'), 'edx': V('cv'), 'ebx': V('ebx0'), 'ebp': V('ebp0'),
                     'esi': V('q'), 'edi': V('edi0')}, 0, 0x1005f2, {})
    s.branch[0x1005f4] = (taken, 'k.toNat ≠ 1' if taken else 'k.toNat = 1')
    for j, p in enumerate(s.run(0x1005f0 if taken else 0x1005f6)):
        out.append(s.lemma(p, 'ms_st' if taken else 'ms_sn'))
s = seg('ms_e', {'eax': V('a0'), 'ecx': V('c0'), 'edx': V('d0'), 'ebx': V('ebx0'), 'ebp': V('ebp0'),
                 'esi': V('q'), 'edi': V('edi0')}, 0, 0x1005f6, {0: V('esi0'), 4: V('ret')})
for j, p in enumerate(s.run(None)):
    out.append(s.lemma(p, 'ms_e%d' % j))
open(os.path.join(D, 'MsRun.lean'), 'w').write(HDR + "".join(out) + "\nend Solutions.OpensslPoly1305\n")
print(len(out), 'pieces')
