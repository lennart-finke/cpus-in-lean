#!/usr/bin/env python3
"""Check the Lean-embedded image against the pinned hashes, symbols, disassembly and build record.

usage: gen_image.py TARGET [--check]
Bytes are stored only in Image.lean; this command verifies that representation and never writes
files. `build.py --pin` is the only writer (it uses `render`).
"""
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CFG = {"images": "targets", "stmt_lib": "Ssl", "stmt_ns": "Ssl"}


def render(target, module, data, syms):
    """Canonical Lean representation; checking it also protects the byte-decoder definitions."""
    sha = hashlib.sha256(data).hexdigest()
    lines = ["/-! Generated by tools/gen_image.py. Do not edit.",
             f"Target: {target}", f"SHA-256: {sha}", "-/", f"namespace {CFG['stmt_ns']}.{module}.Image", "",
             "def base : UInt32 := 0x100000", f"def size : Nat := {len(data)}",
             "def chunkSize : Nat := 512", ""]
    for k, start in enumerate(range(0, len(data), 512)):
        chunk = int.from_bytes(data[start:start+512], "little")
        lines.append(f"def chunk{k} : Nat := 0x{chunk:X}")
    lines += ["", "def chunk : Nat → Nat"]
    lines += [f"  | {k} => chunk{k}" for k in range((len(data)+511)//512)]
    lines += ["  | _ => 0", "", "def byte (i : Nat) : UInt8 :=",
              "  ((chunk (i / chunkSize) >>> (8 * (i % chunkSize))) &&& 255).toUInt8", "",
              "def bytes : ByteArray := ⟨Array.ofFn (n := size) fun i => byte i.val⟩", ""]
    for name, addr in sorted(syms.items()):
        safe = name.replace(".", "_")
        lines.append(f"def sym_{safe} : UInt32 := 0x{addr:X}")
    lines += ["", f"end {CFG['stmt_ns']}.{module}.Image", ""]
    return "\n".join(lines)


def pinned_image(target):
    """Recover the sole stored copy of the bytes, then check every pin and the canonical syntax."""
    tdir = ROOT / "targets" / target
    module = json.loads((tdir / "target.json").read_text())["module"]
    text = (ROOT / "Ssl" / module / "Image.lean").read_text()
    size = int(re.search(r"^def size : Nat := (\d+)$", text, re.M)[1])
    if not 0 < size < 0x100000:
        raise SystemExit(f"{target}: implausible image size")
    chunks = re.findall(r"^def chunk(\d+) : Nat := 0x([0-9A-F]+)$", text, re.M)
    if [int(i) for i, _ in chunks] != list(range((size + 511) // 512)):
        raise SystemExit(f"{target}: missing or out-of-order image chunks")
    data = b"".join(int(value, 16).to_bytes(512, "little") for _, value in chunks)[:size]
    pins = dict((name, digest) for digest, name in
                (line.split() for line in (tdir / "image/SHA256SUMS").read_text().splitlines()))
    files = {p.name: p.read_bytes() for p in (tdir / "image").iterdir() if p.name != "SHA256SUMS"}
    artifacts = {f"{target}.bin": data, **files}
    required = {f"{target}.bin", f"{target}.syms.json", f"{target}.dis", "build.txt"}
    if set(pins) != set(artifacts) or set(pins) != required:
        raise SystemExit(f"{target}: incomplete or unexpected image pins")
    for name, contents in artifacts.items():
        if hashlib.sha256(contents).hexdigest() != pins[name]:
            raise SystemExit(f"{target}: hash mismatch for {name}")
    syms = json.loads(files[f"{target}.syms.json"])
    if text != render(target, module, data, syms):
        raise SystemExit(f"{target}: noncanonical Lean image definitions")
    return data, syms


if __name__ == "__main__":
    if len(sys.argv) not in (2, 3) or (len(sys.argv) == 3 and sys.argv[2] != "--check"):
        raise SystemExit("usage: gen_image.py TARGET [--check]")
    data, _ = pinned_image(sys.argv[1])
    print(f"{sys.argv[1]}: image definitions match {hashlib.sha256(data).hexdigest()}")
