#!/usr/bin/env python3
"""Reference vectors for the Lean specifications, from implementations independent of this suite.

usage: python3 tools/spec_vectors.py            regenerate and compare with tools/spec_vectors.txt
       python3 tools/spec_vectors.py --write    rewrite tools/spec_vectors.txt

SHA-256/SHA-224 come from Python's hashlib; ChaCha20, Poly1305 and X25519 from the `cryptography`
package (`pip install cryptography`). The inputs are fixed edge cases plus a seeded pseudo-random
sample, so the file is reproducible. `sslcheck spec tools/spec_vectors.txt` evaluates the Lean
specifications on every line; that check needs neither Python package nor network.

Not covered by a reference, by design: ChaCha20 runs that overflow the 32-bit block counter (the
reference carries into the nonce, the specification wraps; see `Ssl/Spec/Chacha.lean`) and X25519
inputs whose result is all-zero (the reference refuses them; one is checked in the kernel instead).
"""
import hashlib
import random
import sys
from pathlib import Path

FILE = Path(__file__).with_name("spec_vectors.txt")
P25519 = 2**255 - 19


def h(b):
    return b.hex() or "-"


def generate():
    from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey, X25519PublicKey
    from cryptography.hazmat.primitives.ciphers import Cipher, algorithms
    from cryptography.hazmat.primitives.poly1305 import Poly1305

    rnd = random.Random(20261110)
    lines = ["# Generated by tools/spec_vectors.py; do not edit."]

    # every padding boundary of the 64-byte block, then longer messages
    for n in [*range(0, 4), *range(54, 67), 111, 112, 119, 120, 127, 128, 129, 1000]:
        msg = rnd.randbytes(n)
        lines.append(f"sha256 {h(msg)} {hashlib.sha256(msg).hexdigest()}")
        lines.append(f"sha224 {h(msg)} {hashlib.sha224(msg).hexdigest()}")

    def chacha(key, counter, nonce, pt):
        enc = Cipher(algorithms.ChaCha20(key, counter.to_bytes(4, "little") + nonce), mode=None).encryptor()
        return f"chacha20 {h(key)} {counter:08x} {h(nonce)} {h(pt)} {h(enc.update(pt))}"

    # RFC 8439 section 2.4.2
    lines.append(chacha(bytes(range(32)), 1, bytes.fromhex("000000000000004a00000000"),
                        b"Ladies and Gentlemen of the class of '99: If I could offer you only one tip for "
                        b"the future, sunscreen would be it."))
    for n in [0, 1, 63, 64, 65, 127, 128, 129, 300]:
        for counter in [0, 1, rnd.getrandbits(31), 0xFFFFFFFF - (n + 63) // 64]:   # never overflows
            lines.append(chacha(rnd.randbytes(32), counter, rnd.randbytes(12), rnd.randbytes(n)))

    def poly(key, msg):
        return f"poly1305 {h(key)} {h(msg)} {Poly1305.generate_tag(key, msg).hex()}"

    # RFC 8439 section 2.5.2
    lines.append(poly(bytes.fromhex("85d6be7857556d337f4452fe42d506a80103808afb0db2fd4abff6af4149f51b"),
                      b"Cryptographic Forum Research Group"))
    ff, zero = b"\xff" * 16, bytes(16)
    two = (2).to_bytes(16, "little")
    # carries through 2^130 - 5 and 2^128: maximal r and s, all-ones blocks, tiny r
    for key in [ff + ff, ff + zero, zero + ff, two + zero, two + ff, (1).to_bytes(16, "little") + ff]:
        for msg in [b"", ff, ff * 2, ff * 3, ff + b"\xff", bytes.fromhex("fbffffffffffffffffffffffffffffff"),
                    bytes.fromhex("fdffffffffffffffffffffffffffffff"), ff * 16 + b"\x01"]:
            lines.append(poly(key, msg))
    for n in [*range(0, 34), 47, 48, 49, 255, 256, 257, 1024]:
        lines.append(poly(rnd.randbytes(32), rnd.randbytes(n)))

    def x25519(k, u):
        out = X25519PrivateKey.from_private_bytes(k).exchange(X25519PublicKey.from_public_bytes(u))
        return f"x25519 {h(k)} {h(u)} {out.hex()}"

    le = lambda v: v.to_bytes(32, "little")
    # RFC 7748 section 5.2 (both vectors) and section 6.1 (both public keys and the shared secret)
    lines.append(x25519(bytes.fromhex("a546e36bf0527c9d3b16154b82465edd62144c0ac1fc5a18506a2244ba449ac4"),
                        bytes.fromhex("e6db6867583030db3594c1a424b15f7c726624ec26b3353b10a903a6d0ab1c4c")))
    lines.append(x25519(bytes.fromhex("4b66e9d4d1b4673c5ad22691957d6af5c11b6421e0ea01d42ca4169e7918ba0d"),
                        bytes.fromhex("e5210f12786811d3f4b7959d0538ae2c31dbe7106fc03c3efc4cd549c715a493")))
    alice = bytes.fromhex("77076d0a7318a57d3c16c17251b26645df4c2f87ebc0992ab177fba51db92c2a")
    bob = bytes.fromhex("5dab087e624a8a4b79e17f8b83800ee66f3bb1292618b6fd1c2f8b27ff88e0eb")
    lines.append(x25519(alice, le(9)))
    lines.append(x25519(bob, le(9)))
    lines.append(x25519(alice, bytes.fromhex("de9edb7d7b7dc1b4d35b61c2ece435373f8343c85b78674dadfc7e146f882b4f")))
    # RFC 7748 section 5.2, iterated: k, u = X25519(k, u), k
    k = u = le(9)
    for _ in range(20):
        line = x25519(k, u)
        lines.append(line)
        k, u = bytes.fromhex(line.split()[3]), k
    # non-canonical u (>= p, and with the ignored top bit set), small u, all scalar bits set
    for u in [le(2), le(P25519 - 2), le(P25519 + 2), le(2**255 - 1), le((1 << 255) | 9), b"\xff" * 32]:
        for k in [b"\xff" * 32, bytes(32), rnd.randbytes(32)]:
            lines.append(x25519(k, u))
    for _ in range(20):
        lines.append(x25519(rnd.randbytes(32), rnd.randbytes(32)))
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    text = generate()
    if sys.argv[1:] == ["--write"]:
        FILE.write_text(text)
        print(f"wrote {len(text.splitlines()) - 1} vectors")
    elif FILE.read_text() != text:
        raise SystemExit("tools/spec_vectors.txt differs from what the reference implementations produce")
    else:
        print(f"{len(text.splitlines()) - 1} reference vectors reproduced")
